"""Directory-gallery registry (WP23; ARCHITECTURE.md sections 9, 14.1, 14.5 and 14.8, wave 2).

One adapter ports the jQuery/autoindex galleries: legacy ``gallery*.html`` pages that fetch the
Apache index of their directory (``$.get('./')``) and keep the hrefs matching a JavaScript regex
(``entry.match(/re/i)``: an unanchored, case-insensitive search of the bare file name, the same
as ``re.search(re, name, re.I)``). Each registry entry (:data:`GALLERIES`) is one unified gallery
page; the legacy pages of one directory family become per-file facet presets of that page.

* Facets. A multi-directory page tags every item with ``dir``; every legacy regex that lists a
  subset of its directory becomes a facet ``g_<name>`` with values ``yes``/``no``. The preset of a
  legacy file selects ``{dir: [d], g_<name>: [yes]}``, which reproduces the legacy file list
  exactly and does not depend on the data (the ``--replace`` stubs in the site registry carry the
  same selection as ``fac=<base64url JSON>``; :func:`stub_preset`). Only the brick_2221 pages
  may be stubbed (:data:`STUB_PORTALS`); the other legacy pages stay untouched. Named groups of the ``parse``
  regexes add descriptive facets (dropped when they take more than :data:`MAX_FACET_VALUES`).
* Variant galleries (w51 ``pngs*``, sgrb2 ``pngs*``): the legacy suffix selector becomes image
  roles; ``x.png``, ``x_alma.png``, ``x_log.png`` and ``x_log_alma.png`` (and ``x_best.png``) are
  the roles of one item ``x``.
* Cloud C colour images: ``x_thumbnail.png`` and ``x.png`` (up to 158 MB) are the ``thumb`` and
  ``full`` roles of one item, thumbnails first. Their sizes differ and section 5.10 places w/h per
  role while :class:`ImageItem` carries one w/h (copied onto every role), so these items have none.
* ``png_b``: the Hyperion imaging-run gallery (generated by ``imaging_run/make_gallery.py``) joins
  a catalogue of the model parameters (log10) from ``model_params.ecsv``.
* Item URLs are absolute served URLs under the portal's visibility (pub or secure), so
  ``portalkit thumbs`` can map them to local files.
* Tier A reads each legacy page's regex (``match(/.../i)``) or, for ``png_b``, its card list; Tier B
  uses the declared regexes and the directory (the production path: it keeps working after
  ``--replace`` turns the legacy pages into stubs). Tier C is not implemented.
* Fixed legacy bugs: wrong headers ("ACES mosaics", "W51 Images" on Westerlund pages, "color
  color diagrams" on SEDs, "Brick 2221" on Cloud C and program-1182 diagnostics) get correct
  titles; the w51 top-level page's ``filelist.txt`` fetch (absent everywhere) is gone.

The directories considered and their owners are tabulated in ``sites/dirgallery_sites.toml``.
"""

