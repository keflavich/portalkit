    @staticmethod
    def _spectra(rows: list[dict], meta: dict) -> tuple[CatalogSpec, RecordSetSpec, RecordSetSpec, ImageSetSpec]:
        # an empty string marks an unset classification field (spt/clconf, mainly); keep it
        # out of the inferred category levels by storing it as a null instead.
        clean = [{k: (v if v != "" else None) for k, v in r.items() if k not in _SPEC_ARRAY_FIELDS}
                for r in rows]
        cat = catalog_from_rows(
            clean, id="n", ra="ra", dec="dec", key="spec_cat",
            title=f"GTC/EMIR extracted spectra ({len(rows)})",
            roles={"tier": "category", "std": "category", "stdk": "category", "spc": "category",
                  "field": "category", "objsl": "text", "sid": "text", "litref": "text",
                  "spwhy": "text"})
        cat.caveats = [s for s in (meta.get("note", ""), meta.get("caveat", "")) if s]
        lines = [{"name": str(nm), "w": float(w), "cat": str(cat_), "origin": list(org)}
                for w, nm, cat_, org in (meta.get("lines") or [])]
        by_id = {str(r["n"]): r for r in rows}
        ids = list(by_id)

        def loader(rid: str) -> Spectrum | None:
            return _row_spectrum(by_id.get(rid), lines)

        spec = RecordSetSpec(key="spec", kind="pks1", catalog="spec_cat", ids=ids, loader=loader,
                             noun=("spectrum", "spectra"))
        ids2d = [rid for rid, r in by_id.items() if r.get("twod")]

        def png(rid: str) -> tuple[str, list[float]] | None:
            r = by_id.get(rid)
            if r is None or not r.get("twod"):
                return None
            path = LEGACY / "spectra2d" / f"{rid}_2d.png"
            if not path.is_file():
                return None
            w, h = _png_size(path)
            w0, dw, m = float(r["w0"]), float(r["dw"]), int(r["m"])
            return _surl(f"spectra2d/{rid}_2d.png"), {"w": [w0, w0 + dw * m], "y": [0.0, float(h)]}

        spec2d = RecordSetSpec(key="spec2d", kind="pki1", catalog="spec_cat", ids=ids2d,
                               loader=lambda rid: None, png=png, noun=("2D spectrum", "2D spectra"))
        # legacy spectra.html also shows a pre-rendered static plot PNG (`spectra/<id>.png`,
        # every row has one) with a lightbox zoom on click -- ported as an ImageSetSpec so the
        # detail pane's lightbox capability (section 8.1 "img" flag) applies, same pattern as
        # gallery.html's gal_img.
        img_rows = [{"n": rid, "plot": _surl(f"spectra/{rid}.png")} for rid in ids
                   if (LEGACY / "spectra" / f"{rid}.png").is_file()]
        spec_img = ImageSetSpec.from_rows(img_rows, roles={"plot": "plot"}, id="n", caption=None,
                                          catalog="spec_cat", key="spec_img")
        return cat, spec, spec2d, spec_img

