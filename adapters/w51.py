"""W51 unified portal adapter (WP29, wave 5; ARCHITECTURE.md port table 14.10).

Legacy portal: ``/orange/adamginsburg/w51/portal`` (secure), generated by the
``W51_Portal_*.py`` scripts in the same directory. Ten pages port here (one secure
``[[portal]]``, ``sites/w51.toml``): ``index``, ``map``, ``map_ccd``, ``colorcolor``,
``gallery``, ``spectra``, ``spectra_candidate``, ``w51_manifold``, ``w51_catalog_manifold``,
``wavelength``. The eleventh legacy card (``archive_colors/index.html``) is a different
family and portal (``jwst_archive``, WPE7/WP28,
``https://data.rc.ufl.edu/secure/adamginsburg/w51/portal/archive_colors/unified/``); the
landing page only links to it.

Tier A only (``tiers = ("A",)``): every page's data is already fully present in its legacy
HTML's embedded JSON payload (``portalkit.legacy.extract``), so Tier A already gives full
fidelity and is also the parity oracle; a Tier B reimport of the ``W51_Portal_*.py``
generators would rebuild the same numbers from the underlying FITS catalogues at much higher
cost for no gain in what is tested. Tier A/B parity (contract test (f)) is accordingly
vacuous for this adapter. One consequence: ``map_ccd.html``'s two background catalogues ship
only their quality-filtered rows (48,474 of 135,966; 32,578 of 53,609) -- the full
unfiltered background arrays live only in the raw FITS tables that ``W51_Portal_MapCCD.py``
reads with ``Table.read()``, a Tier B operation this adapter does not perform (contract_issue).

Dataset consolidation: ``map.html``'s own 2557-row ``srcdata`` is a subset of
``gallery.html``'s 2803-row ``srcdata`` (2557 selected sources + 246 ALMA/VLA radio sources,
tagged ``alma-source``/``vla-source`` in the shared ``sel`` field), so both pages share one
catalog (``gal``) built from the larger payload; ``map.html``'s narrower ``srcdata`` and its
``extdata``/``extsed`` (the same 246 radio sources' positions and SEDs, duplicated) are not
separately parsed. ``gallery.html``'s ``sel`` field is a comma-joined tag string
(``"luminous,gtc"``); :func:`_gallery` decomposes it into boolean ``is_red``/``is_luminous``/
``is_alma``/``is_vla``/``is_gtc``/``is_radio`` columns as well as keeping ``sel`` itself.
``map.html``'s 229-row ``gtcdata`` (GTC slit polygons, placement tiers, suspected artifacts)
becomes a sky :class:`~portalkit.spec.OverlaySpec` (``gtc_ovl``): one polygon layer per tier
plus a circles layer (radius from ``perr``) for the 63 rows flagged ``suspect``. (The legacy
page's marker shapes square/triangle/cross, a separate hover-marker encoding, are not
reproduced; only the slit/tier/ring overlays the work package asks for are.) ``gtcdata``'s
``n`` field is the same id as ``spectra.html``'s ``specdata`` rows (``spec_cat``/``spec``),
so a GTC polygon's ``label`` already carries a spectrum-record id for the generic bare-id
lookup grammar; no further per-item linkage field exists in the frozen ``OverlaySpec`` item
schema to wire a direct click-through.

Identity migration: ``w51_catalog_manifold.html``'s 22,260 stars still carry the old
sequential ``W51-NNNNNN`` ids. :func:`_catalog_manifold` recomputes positional ids
(``W51-JW-J<HHMMSS.sss><+/-DDMMSS.ss>``, the same sexagesimal convention and prefix already
used by the main ``gal`` catalog's own ids, per ARCHITECTURE.md's port-table note for this
page) from each star's ra/dec and keeps the old id as an alias, so the legacy ``w51-rowid``
grammar (``#W51-000123`` -> alias lookup, ARCHITECTURE.md section 6.4 / grammar table) keeps
resolving. Each star's boolean ``sed`` flag becomes the ``seds_catalog/<old id>.png`` URL
(or ``None``) before conversion, so the stored column infers role ``url`` instead of
``flag``. ``map_ccd.html``'s two background catalogues carry no id field at all; they get the
same positional-id treatment under distinct synthetic prefixes (``W51-CCD-WIDE``/
``W51-CCD-JWST``) -- there is nothing to alias since no legacy id ever existed for these
rows. ``map_ccd.html``'s ``jwst`` catalogue's magnitudes are centimag integers (divide by
100); its ``wide`` catalogue's are already plain floats.

``spectra_candidate`` stays BLOCKED (open question Q2: its inputs live in another session's
tmp scratchpad, ``W51_Portal_SpectraCandidate.py``'s hardcoded ``SP``). :func:`_candidate`
looks for the approved, permanent location first (``/orange/adamginsburg/w51/gtc/candidate_xb5``);
absent that, it registers the legacy tmp path with ``ctx.inputs.add`` and lets
:class:`~portalkit.context.BlockedInput` propagate uncaught (checked, deliberately, before
any other dataset is built, so a blocked build fails fast) -- a normal
``portalkit build w51`` (no ``--allow-tmp-inputs``) refuses with exit 5 for the whole family,
since ``datasets()`` builds every page's datasets in one call. ``--allow-tmp-inputs`` is for
staging-only test builds (never deployable); even then the candidate dataset stays a 0-row
placeholder (its real per-object format is unscoped for this work package). The legacy
``spectra_candidate.html`` keeps serving (``replace = false`` in ``sites/w51.toml``).

Nothing under ``/orange/adamginsburg/w51/portal`` is written by this adapter.
"""

