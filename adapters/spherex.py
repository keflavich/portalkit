    def _seds(self, raw, ssel):
        from astropy.table import Table
        from portalkit.spec import CatalogSpec, ColumnSpec, Preset
        recs = [raw["seds"][i] for i in ssel]
        t = Table()
        t["id"] = [str(d["id"]) for d in recs]
        t["ra"] = _arr([d.get("ra") for d in recs])
        t["dec"] = _arr([d.get("dec") for d in recs])
        cols = [ColumnSpec("id", "id"), ColumnSpec("ra", "ra", unit="deg"), ColumnSpec("dec", "dec", unit="deg")]
        cls = [str(d.get("cls") or "unclassified") for d in recs]
        fq = [str(d.get("fq") or "unknown") for d in recs]
        t["cls"], t["fq"] = cls, fq
        cols.append(ColumnSpec("cls", "category", label="Class", levels=sorted(set(cls))))
        flv = [x for x in FQ_COLORS if x in fq] + sorted(set(fq) - set(FQ_COLORS))
        cols.append(ColumnSpec("fq", "category", label="Far-IR verdict", levels=flv,
                               colors={k: v for k, v in FQ_COLORS.items() if k in flv},
                               note="WISE 22 µm crowding and IRAS cirrus verdict for the far-IR points"))
        # photometry: one flux (+ error) column per band, first point kept on duplicates
        bands: dict[str, dict] = {}
        dup = 0
        per = []
        for d in recs:
            got = {}
            for wl, f, e, origin, band in d.get("p") or []:
                k = band_key(band)
                b = bands.setdefault(k, {"band": band.replace(EXT_SUFFIX, ""), "wl": [], "origin": origin,
                                         "ext": 0})
                if k in got:
                    dup += 1
                    continue
                b["wl"].append(float(wl))
                if band.endswith(EXT_SUFFIX):
                    b["ext"] += 1
                got[k] = (f, e, band.endswith(EXT_SUFFIX))
            per.append(got)
        order = sorted(bands, key=lambda k: (float(np.median(bands[k]["wl"])), k))
        self._sed_bands = {k: bands[k] for k in order}
        for k in order:
            b = bands[k]
            t[f"p_{k}"] = _arr([g[k][0] if k in g else None for g in per])
            t[f"e_{k}"] = _arr([g[k][1] if k in g else None for g in per])
            note = f"{b['origin']}; {float(np.median(b['wl'])):g} µm"
            if b["ext"]:
                note += f"; flagged extended for {b['ext']} star(s) (see ext_bands)"
            cols.append(ColumnSpec(f"p_{k}", "flux", label=b["band"], unit="uJy", filter=self._filter_key(b["band"]),
                                   err=f"e_{k}", group="phot", note=note))
            cols.append(ColumnSpec(f"e_{k}", "error", label=f"{b['band']} error", unit="uJy", group="phot"))
        t["ext_bands"] = [", ".join(bands[k]["band"] for k in order if k in g and g[k][2]) for g in per]
        num = lambda f: _arr([d.get(f) for d in recs])  # noqa: E731
        lam = [[float(q[0]) for q in d.get("p") or []] for d in recs]
        vals = (("ks", num("ks"), "Ks (2MASS)", "mag", "", True),
                ("l", num("l"), "Galactic l", "deg", "", None), ("b", num("b"), "Galactic b", "deg", "", None),
                ("n60", num("n60"), "22 µm neighbours < 60″", "", "", None),
                ("n120", num("n120"), "22 µm neighbours < 120″", "", "", None),
                ("cf60", num("cf60"), "Neighbour flux share < 60″", "", "fraction of the WISE 22 µm flux within 60″ "
                 "held by neighbours (legacy sort: least confused)", None),
                ("cf120", num("cf120"), "Neighbour flux share < 120″", "", "", None),
                ("c2", num("c2"), "IRAS cirrus ratio (cirr2, 1–9)", "", "", None),
                ("c3", num("c3"), "IRAS 100 µm sky", "MJy/sr", "", None),
                ("cfl", num("cfl"), "IRAS confusion flag", "", "", None),
                ("nalma", num("alma"), "ALMA observations", "", "", None),
                ("hobs", num("hobs"), "Herschel observations", "", "", None),
                ("nphot", np.array([float(len(x)) for x in lam]), "Photometry points", "", "", None),
                ("nfir", np.array([float(sum(w >= 20 for w in x)) for x in lam]), "Points at ≥ 20 µm", "",
                 "legacy default sort", None),
                ("lammax", np.array([max(x) if x else np.nan for x in lam]), "Longest wavelength", "µm", "", None))
        for k, v, lab, unit, note, inv in vals:
            t[k] = v
            if np.isfinite(v).any():
                cols.append(ColumnSpec(k, "value", label=lab, unit=unit, note=note, invert=inv))
            else:
                del t[k]
        flags = (("alma", [bool(d.get("alma")) for d in recs], "ALMA"),
                 ("alma_pointed", [bool(d.get("atgt")) for d in recs], "ALMA pointed at the star"),
                 ("herschel", [bool(d.get("hobs")) for d in recs], "Herschel observed"),
                 ("fir60", [bool(x) and max(x) >= 60 for x in lam], "Photometry at ≥ 60 µm"),
                 ("uncrowded", [x in ("clean", "usable") for x in fq], "Uncrowded (clean or usable)"),
                 ("spherex", [d.get("i") is not None for d in recs], "Has a SPHEREx spectrum"))
        for k, v, lab in flags:
            t[k] = np.array(v, dtype=bool)
            cols.append(ColumnSpec(k, "flag", label=lab))
        iras = [str(d.get("iras") or "").strip() for d in recs]
        t["iras"] = [x if x and x != "--" else "none within 40″" for x in iras]
        t["abands"] = [str(d.get("abands") or "") for d in recs]
        t["aprog"] = [str(d.get("aprog") or "") for d in recs]
        t["hins"] = [str(d.get("hins") or "") for d in recs]
        t["hprog"] = [str(d.get("hprog") or "") for d in recs]
        t["notes"] = [sed_notes(d) for d in recs]
        cols += [ColumnSpec("iras", "text", label="IRAS source"), ColumnSpec("abands", "text", label="ALMA bands"),
                 ColumnSpec("aprog", "text", label="ALMA projects"), ColumnSpec("hins", "text", label="Herschel instruments"),
                 ColumnSpec("hprog", "text", label="Herschel programs"),
                 ColumnSpec("ext_bands", "text", label="Bands flagged extended"),
                 ColumnSpec("notes", "text", label="Confusion notes", note="the legacy sed.html notes")]
        presets = [Preset(f"chip_{k}", lab, "filter", {"filters": {"flags": {k: 1}}})
                   for k, v, lab in flags if k != "spherex" and any(v)]
        if "nfir" in t.colnames and "lammax" in t.colnames:
            presets.append(Preset("fir_reach", "Longest wavelength vs far-IR points", "axes", {"x": "lammax", "y": "nfir"}))
        caveats = ["Fluxes are in µJy as the legacy page stored them (Jy from IRSA and mJy from the Herschel "
                   "catalogues converted at build time of the legacy portal).",
                   "IRAS beams are arcminutes across: for confused stars the IRAS points are an upper envelope."]
        if dup:
            caveats.append(f"{dup} duplicate (star, band) point(s): the first point of each band is kept.")
        return CatalogSpec(key="seds", table=t, id="id", ra="ra", dec="dec", columns=cols, presets=presets,
                           title=f"R CrB / HdC far-IR SEDs ({len(t):,})", noun=("star", "stars"), caveats=caveats)

    @staticmethod
    def _filter_key(band: str) -> str:
        return BAND_FILTERS.get(band, f"SED/{band}")

    def _filters(self, raw, seds):
        from portalkit.physics.filters import lookup
        from portalkit.spec import FilterSetSpec
        keys = [f"JWST/NIRCam.{s}" for s in raw["filters"]]
        extra = {}
        w4 = WISE_ZP["WISE/WISE.W4"]
        for k, b in self._sed_bands.items():
            fk = self._filter_key(b["band"])
            if fk in keys or fk in extra:
                continue
            if lookup(fk) is not None:
                keys.append(fk)
                continue
            wl = WISE_ZP[fk][0] if fk in WISE_ZP else round(float(np.median(b["wl"])), 4)
            zp = WISE_ZP[fk][1] if fk in WISE_ZP else round(w4[1] * (w4[0] / wl) ** 2, 6)
            extra[fk] = {"wl_um": wl, "zp_jy": zp, "label": b["band"].replace("_", " "),
                         "instrument": b["band"].split("_")[0], "system": "Vega"}
        return FilterSetSpec(keys=keys, extra=extra)

