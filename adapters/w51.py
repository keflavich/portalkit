    @staticmethod
    def _ccd_jwst(d: dict) -> CatalogSpec:
        ra = np.asarray(d["R"], dtype=np.float64)
        dec = np.asarray(d["D"], dtype=np.float64)
        n = len(ra)
        ids = positional_ids("W51-CCD-JWST", ra, dec)
        t = Table()
        t["id"] = ids
        t["ra"] = ra
        t["dec"] = dec
        cols: list[ColumnSpec] = []
        for f, vals in (d.get("M") or {}).items():
            inst = "MIRI" if f in MIRI_FILTERS else "NIRCam"
            # map_ccd.html's jwst catalogue stores centimag integers; its wide catalogue
            # (handled by _ccd_wide) is already plain float magnitudes.
            t[f] = np.asarray(vals, dtype=np.float64) / 100.0
            cols.append(ColumnSpec(f, "mag", label=f.upper(), unit="mag",
                                   filter=f"JWST/{inst}.{f.upper()}", step=0.001))
        for f, vals in (d.get("Q") or {}).items():
            key = f"{f}_snr"
            t[key] = np.asarray(vals, dtype=np.float64)
            cols.append(ColumnSpec(key, "value", label=f"{f.upper()} S/N",
                                   note="0 means not measured in this filter; capped at 100"))
        ccd4 = list(d.get("ccd") or [])
        cmd3 = list(d.get("cmd") or [])
        pairs = []
        if len(ccd4) == 4:
            pairs += [(ccd4[0], ccd4[1]), (ccd4[2], ccd4[3])]
        if len(cmd3) == 3:
            pairs.append((cmd3[0], cmd3[1]))
        virt: list[VirtualDim] = []
