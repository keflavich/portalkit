def legacy_sections(md: str, keep=("R Coronae Borealis stars", "The far-infrared SED page",
                                   "Quality flags rather than a QC cut", "Template overlays",
                                   "Band coverage at the red end", "Spitzer IRS spectra", "Reading the diagrams")) -> str:
    """The ``keep`` sections (with their subsections) of the legacy README, headings demoted one
    level and absolute filesystem paths replaced, so nothing served names /orange, /blue or /home."""
    parts = re.split(r"(?m)^(?=## )", md)
    out = []
    for p in parts:
        head = p.splitlines()[0][3:].strip() if p.startswith("## ") else None
        if head in keep:
            body = re.sub(r"(?m)^(#{2,5}) ", lambda m: "#" + m.group(1) + " ", p.rstrip())
            out.append(scrub_paths(body))
    return "\n\n".join(out)


def scrub_paths(s: str) -> str:
    return re.sub(r"(?<![\w.:/])/(?:orange|blue|home)/[^\s`)\]'\"]*", "(legacy tree)", s)


class SpecLoader:
    """id -> SPHEREx (+ Spitzer IRS) spectrum from ``spectra/<i>.json`` (µJy -> Jy)."""

    def __init__(self, root: Path, idx: dict):
        self.root, self.idx = Path(root), dict(idx)

    def read(self, sid: str):
        i = self.idx.get(str(sid))
        if i is None:
            return None
        path = self.root / f"{i}.json"
        if not path.is_file():
            return None
        d = json.loads(path.read_text(encoding="utf-8"))
        if d.get("id") is not None and str(d["id"]) != str(sid):
            raise ValueError(f"{path} holds {d['id']!r}, expected {sid!r}: spectra/ and the page payload are "
                             "from different legacy builds")
        return d

    @staticmethod
    def segments(d: dict) -> list[tuple[str, np.ndarray, np.ndarray, np.ndarray]]:
        out = []
        for label, kw, kf, ke in (("SPHEREx", "w", "f", "e"), ("IRS", "iw", "if", "ie")):
            w = _arr(d.get(kw) or [])
            if not w.size:
                continue
            f = _arr(d.get(kf) or [None] * w.size) * 1e-6
            e = _arr(d.get(ke) or [None] * w.size) * 1e-6
            ok = np.isfinite(w) & (w > 0)
            w, f, e = w[ok], f[ok], e[ok]
            o = np.argsort(w, kind="stable")
            out.append((label, w[o], f[o], e[o]))
        return out

    def __call__(self, sid: str):
        from portalkit.spec import Spectrum
        d = self.read(sid)
        if d is None:
            return None
        segs = self.segments(d)
        if not segs or not any(s[1].size for s in segs):
            return None
        wave, flux, err, spans, i0 = [], [], [], [], 0
        for label, w, f, e in segs:
            wave.append(w)
            flux.append(f)
            err.append(e)
            spans.append((i0, i0 + w.size, label))
            i0 += w.size
        return Spectrum(wave=np.concatenate(wave), channels={"flux": np.concatenate(flux), "err": np.concatenate(err)},
                        units={"flux": "Jy", "err": "Jy"}, segments=spans,
                        meta={"sample": d.get("s"), "irs": any(s[0] == "IRS" for s in segs)})


class SedCurveLoader:
    """id -> the same spectrum as a sedcurve record with one channel per instrument, named for
    the sed pane's legend: ``SPHEREx`` and ``IRS`` (the Spitzer IRS spectrum), each NaN outside
    its own wavelengths so the sed pane draws two curves."""

    CHANNELS = ("SPHEREx", "IRS")

    def __init__(self, spec: SpecLoader):
        self.spec = spec

    def __call__(self, sid: str):
        from portalkit.spec import Spectrum
        d = self.spec.read(sid)
        if d is None:
            return None
        segs = [s for s in self.spec.segments(d) if s[1].size]
        if not segs:
            return None
        wave = np.concatenate([s[1] for s in segs])
        o = np.argsort(wave, kind="stable")
        ch = {}
        for name in self.CHANNELS:
            v = np.concatenate([s[2] if s[0] == name else np.full(s[1].size, np.nan) for s in segs])
            ch[name] = v[o]
        return Spectrum(wave=wave[o], channels=ch, units={c: "Jy" for c in self.CHANNELS})


