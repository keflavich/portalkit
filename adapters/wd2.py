"""Westerlund 2 family adapter (WP24; ARCHITECTURE.md sections 9 and 14.11).

Legacy portal: ``web/public/jwst/wd2/nirspec_2640`` (shared with the NIRSpec 2640 family, so
the unified portal deploys to ``unified/wd2/``), generated by ``WD2_Portal_{MapCCD,
ColorColor,Manifold,Sabbi,SEDGallery,WavelengthExplorer}.py`` in
``/orange/adamginsburg/jwst/brick/analysis``.

* Tier A reads the legacy payloads: ``DATA`` of ``wd2_manifold.html`` and ``sabbi.html``,
  the ``ccddata`` JSON of ``map_ccd.html`` (with its ``BASES``/``OVERLAYS``/``CENTER``),
  ``waypoints_wd2_wavelength.json`` and the ``SURVEYS`` list of the manifold page.
* Tier B imports the generators and rebuilds the same payloads (``build`` + ``standardize``
  + the ``main()`` preset/PCA steps, ``jwst_dataset``, ``S.build``), memoised in ctx.cache.

Both tiers then go through the same converters. Shared by both tiers: the colour-colour
diagram list (``DIAGRAMS`` of ``wd2_colorcolor.html``; its MIRI entries are local to
``build_miri_diagrams``), the SED-fit table ``wd2_sed_fits.ecsv`` (which names the stars with
an SED figure) and the catalogue RA/Dec, used to give the map_ccd rows their catalogue row
ids (``WD2-<row>``, the manifold naming) by an ordered walk over the 5-decimal positions.
Colours that equal a difference of two stored magnitudes become virtual dims. The NIRSpec
spectra stay in the NIRSpec 2640 portal: the manifold page plots them through a foreign record
set (``nirspec``: that portal's ``data/spec/`` shards, matched on the ``spec`` column, which holds
the NIRSpec 2640 source name), and each star also links to its page there (``spec_url``).
Both portals are public, so the public wd2 portal may reference those shards.

HST bands: the filter registry carries WFC3/ACS curves, but the Sabbi+2020 master catalogue
names its bands only Im/V/J/H (``WD2_Portal_Sabbi.py``: "not a specified ACS/WFC3 bandpass"),
so no ``m_hst_*`` column gets a filter curve. ``HST_BANDPASS`` maps a band to a registry key
once the bandpass is known; it is empty on purpose.
"""

