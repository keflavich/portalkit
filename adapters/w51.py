    @staticmethod
    def _colorcolor(rows: list[dict], panels: list[dict], meta: dict | None = None) -> CatalogSpec:
        meta = meta or {}
        ra = np.array([r.get("ra", np.nan) for r in rows], dtype=np.float64)
        dec = np.array([r.get("dec", np.nan) for r in rows], dtype=np.float64)
        ids = [str(r["n"]) for r in rows]
        t = Table()
        t["id"] = ids
        t["ra"] = ra
        t["dec"] = dec
        t["sel"] = [str(r.get("sel") or "") for r in rows]
        cols = [ColumnSpec("sel", "category", label="Selection reason")]
        presets = []
        for i, p in enumerate(panels):
            xk, yk, qk = f"p{i}_x", f"p{i}_y", f"p{i}_q"
            vx = np.full(len(rows), np.nan)
            vy = np.full(len(rows), np.nan)
            vq = np.zeros(len(rows), dtype=bool)
            for j, r in enumerate(rows):
                v = r.get("v")
                q = r.get("q")
                # v[i] can itself be [None, <float>] or [<float>, None] -- only one axis of
                # this panel's colour pair unmeasured for this star; each component is kept
                # or NaN'd independently (regression test for the crash fixed this work
                # package: float(None) on the whole-pair gate, test_colorcolor_v_component_
                # can_be_none).
                if v and i < len(v) and v[i] is not None:
                    ax, ay = v[i]
                    if ax is not None:
                        vx[j] = float(ax)
                    if ay is not None:
                        vy[j] = float(ay)
                if q and i < len(q) and q[i] is not None:
                    vq[j] = bool(q[i])
            t[xk], t[yk], t[qk] = vx, vy, vq
            label = p.get("label", f"panel {i}")
            # a 'cmd' panel's y axis (p.get('yf')) is a single real filter magnitude, not a
            # colour (map_ccd.html/colorcolor.html convention: kind 'cmd' -> len(yf) == 1);
            # giving it role 'mag' with the filters-registry key (instead of 'value') is what
            # lets the page's mags2/mags3f data flags see it (cmd_ccd_scatter, av_slider,
            # extinction_vectors_on_ccd -- section 8.1).
            yf = list(p.get("yf") or [])
            if p.get("kind") == "cmd" and len(yf) == 1:
                f = str(yf[0]).lower()
                inst = "MIRI" if f in MIRI_FILTERS else "NIRCam"
                y_col = ColumnSpec(yk, "mag", label=p.get("ylabel", "y"), unit="mag",
                                   filter=f"JWST/{inst}.{f.upper()}")
            else:
                y_col = ColumnSpec(yk, "color", label=p.get("ylabel", "y"), unit="mag")
            cols += [ColumnSpec(xk, "color", label=p.get("xlabel", "x"), unit="mag"), y_col,
                    ColumnSpec(qk, "flag", label=f"{label}: meets background quality cut")]
            presets.append(Preset(f"panel{i}", label, "axes", {"x": xk, "y": yk}))
        return CatalogSpec(
            key="ccx", table=t, id="id", columns=cols, ra="ra", dec="dec", presets=presets,
            title=f"W51 colour diagrams ({len(rows):,} selected sources)",
            caveats=[s for s in (meta.get("note", ""), meta.get("caveat", "")) if s])

    # -- colorcolor: MIST isochrones + G23 extinction + background density context ------------

    @staticmethod
    def _isochrones(isodata: dict) -> IsochroneSpec:
        """``colorcolor.html``'s embedded ``isodata`` (``dm``, ``k`` per-filter A_lambda/A_V,
        5 MIST tracks of ``label``/``logage``/``mass``/per-filter ``m``) -> an
        :class:`IsochroneSpec`. The legacy grid carries no metallicity field; tracks are
        labeled solar (``feh=0.0``) for display only, a caveat on the page."""
        dm = float(isodata.get("dm") or 0.0)
        dist_pc = 10.0 ** (dm / 5.0 + 1.0)
        tracks = []
        for t in isodata.get("tracks") or []:
            mass = np.asarray(t.get("mass") or [], dtype=np.float64)
            mags = {str(f): np.asarray(arr, dtype=np.float64) for f, arr in (t.get("m") or {}).items()}
            age_myr = 10.0 ** float(t.get("logage", 6.0)) / 1.0e6
            tracks.append(Track(label=str(t.get("label", "")), age_myr=age_myr, dist_pc=dist_pc,
                                feh=0.0, mass=mass, mags=mags))
        return IsochroneSpec(tracks=tracks)

    @staticmethod
    def _ccx_background(jwst_raw: dict, panels: list[dict]) -> CatalogSpec:
        """A density-only background catalogue (``context=True``) for the ``colorcolor``
        scatter panels, from ``map_ccd.html``'s full (unsliced by ``ctx.limit``) ``jwst``
        catalogue restricted to the filters ``colorcolor.html``'s panels actually use --
        ARCHITECTURE.md port table 14.10's "client density from the ... background (context)
        dataset is the default". One :class:`DensitySpec` grid per panel, over the panel's own
        legacy ``xlim``/``ylim`` extent."""
        filters: list[str] = []
        for p in panels:
            for f in list(p.get("xf") or []) + list(p.get("yf") or []):
                f = str(f).lower()
                if f not in filters:
                    filters.append(f)
        ra = np.asarray(jwst_raw["R"], dtype=np.float64)
        dec = np.asarray(jwst_raw["D"], dtype=np.float64)
        ids = positional_ids("W51-CCXBG", ra, dec)
        t = Table()
        t["id"] = ids
        t["ra"] = ra
        t["dec"] = dec
        cols = []
        m = jwst_raw.get("M") or {}
        for f in filters:
            if f not in m:
                continue
            inst = "MIRI" if f in MIRI_FILTERS else "NIRCam"
            t[f] = np.asarray(m[f], dtype=np.float64) / 100.0
            cols.append(ColumnSpec(f, "mag", label=f.upper(), unit="mag",
                                   filter=f"JWST/{inst}.{f.upper()}"))
        density = []
        for i, p in enumerate(panels):
            xf, yf = list(p.get("xf") or []), list(p.get("yf") or [])
            if len(xf) != 2 or not yf or any(f not in m for f in xf + yf):
                continue
            xk = f"{xf[0]}-{xf[1]}"
            yk = f"{yf[0]}-{yf[1]}" if len(yf) == 2 else yf[0]
            xlim, ylim = p.get("xlim"), p.get("ylim")
            density.append(DensitySpec(f"ccxbg{i}", xk, yk,
                                       xr=tuple(xlim) if xlim else None,
                                       yr=tuple(ylim) if ylim else None))
        return CatalogSpec(
            key="ccx_bg", table=t, id="id", columns=cols, ra="ra", dec="dec", density=density,
            context=True, exact_rows=False,
            title=f"NIRCam+MIRI background ({len(ra):,} sources)",
            caveats=["Background density for the colour diagrams; quality-filtered JWST "
                    "photometry, same catalogue as map_ccd.html's 'jwst' background."])

