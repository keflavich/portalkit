def test_replace_refusals(world, tmp_path):
    with pytest.raises(OwnershipConflict) as ei:
        run(world, site(world, legacy=("../escape.html",)))
    assert ei.value.exit_code == 4
    outside = tmp_path / "outside.html"
    outside.write_text("x")
    os.symlink(outside, world["legacy"] / "linked.html")
    with pytest.raises(SymlinkRefusal) as ei:
        run(world, site(world, legacy=("linked.html",)))
    assert ei.value.exit_code == 3
    assert outside.read_text() == "x"
    assert not (world["legacy"] / ".portalkit_backup").exists()
    s = site(world)
    del s["portal"][0]["legacy_dir"]
    s["portal"][0]["target_dir"] = str(world["target"])
    with pytest.raises(UsageError):
        run(world, s)


def test_validate_backup_errors():
    assert bmod.validate_backup([]) == ["backup.json must be an object"]
    errs = bmod.validate_backup({"schema": "x", "files": [{"file": "../a", "size": "1"}]})
    text = " ".join(errs)
    assert "schema" in text and "size" in text and "relative" in text and "md5" in text
