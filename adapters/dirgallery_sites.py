def js_regex(src: str) -> re.Pattern:
    """A legacy ``/src/i`` regex as a Python pattern (used with ``search``)."""
    return re.compile(src, re.I)


def legacy_regexes(path: os.PathLike | str) -> list[str]:
    """The distinct file-filter regexes of a legacy jQuery gallery (``match(/.../flags)``), in
    order; the suffix-group regex of the variant galleries is left out."""
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    return list(dict.fromkeys(p for p, _ in _MATCH.findall(text) if not p.startswith("(_")))


def facet_key(lg: Legacy) -> str:
    stem = Path(lg.file).stem
    stem = stem[len("gallery_"):] if stem.startswith("gallery_") else stem
    return "g_" + re.sub(r"[^a-z0-9]+", "_", stem.lower()).strip("_")


def preset_facets(g: Gallery, src: Source, lg: Legacy) -> dict:
    """Facet selection that reproduces one legacy page (empty: the whole page)."""
    out = {}
    if len(g.sources) > 1:
        out["dir"] = [src.label]
    if lg.subset:
        out[facet_key(lg)] = ["yes"]
    return out


def legacy_url(vis: str, g: Gallery, lg: Legacy) -> str:
    """Served URL of a legacy page: the served path of the portal's ``legacy_dir`` (the first
    source's served path minus its first legacy page's directory) plus ``lg.file``."""
    s, d = g.sources[0], os.path.dirname(g.sources[0].legacy[0].file)
    if d and not (s.served == d or s.served.endswith("/" + d)):
        raise ValueError(f"{g.page}: {s.served!r} does not end in the legacy directory {d!r}")
    root = s.served[:len(s.served) - len(d)].rstrip("/")
    return PREFIX[vis] + quote(f"{root}/{lg.file}" if root else lg.file)


def stub_preset(facets: dict) -> str | None:
    """``fac=<base64url JSON>`` hash of a facet selection (web/js/core/hash.js)."""
    if not facets:
        return None
    raw = json.dumps(facets, separators=(",", ":"), sort_keys=True).encode("utf-8")
    return "fac=" + base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")


def _take(rows: list[dict], limit: int | None, key) -> list[dict]:
    """``limit`` rows, round-robin over the groups of ``key`` (fixture mode keeps every
    preset populated); ``None`` keeps all."""
    if limit is None or len(rows) <= limit:
        return rows
    groups: dict = {}
    for r in rows:
        groups.setdefault(key(r), []).append(r)
    lists, out, i = list(groups.values()), [], 0
    while len(out) < limit:
        for lst in lists:
            if i < len(lst) and len(out) < limit:
                out.append(lst[i])
        i += 1
    keep = {id(r) for r in out}
    return [r for r in rows if id(r) in keep]


def _fmt(v: float, spec: str) -> str:
    return format(v, spec) if math.isfinite(v) else "?"


class DirGallerySitesAdapter:
    name = "dirgallery_sites"
    tiers = ("A", "B")

    # -- datasets -------------------------------------------------------------------------
    def datasets(self, ctx):
        from portalkit.spec import ReadmeSpec, TierUnavailable
        if ctx.tier not in self.tiers:
            raise TierUnavailable(f"{self.name}: tier {ctx.tier} is not implemented (tiers A and B)")
        ds: dict = {}
        for g in GALLERIES:
            vis = ctx.site.portal(g.portal).visibility
            if g.sources[0].kind == "pngb":
                ds[g.page], ds["pngb"] = self._pngb(ctx, g, vis)
            else:
                ds[g.page] = self._images(ctx, g, vis)
        for p in ctx.site.portals:
            ds[f"readme_{p.id}"] = ReadmeSpec(markdown=self._readme(ctx, p, ds))
        return ds

    def _regex(self, ctx, lg: Legacy, ldir: str) -> str:
        if ctx.tier == "B":
            return lg.rx
        from portalkit.spec import TierUnavailable
        path = os.path.join(ldir, lg.file)
        ctx.inputs.add(path)
        found = legacy_regexes(path)
        if not found:
            raise TierUnavailable(f"{path}: no legacy match() regex (replaced by a stub?); use tier B")
        return "|".join(f"(?:{p})" for p in found)

    def _images(self, ctx, g: Gallery, vis: str):
        from portalkit.spec import ImageItem, ImageSetSpec, Preset
        ldir = ctx.site.portal(g.portal).legacy_dir
        multi = len(g.sources) > 1
        rows: list[dict] = []
        for src in g.sources:
            local = os.path.join(WEB[vis], src.served)
            ctx.inputs.add(local)
            rxs = {lg: js_regex(self._regex(ctx, lg, ldir)) for lg in src.legacy}
            listed = [e for e in os.scandir(local)
                      if e.name.lower().endswith(EXTS) and any(r.search(e.name) for r in rxs.values())]
            names = sorted((e.name for e in listed if e.is_file()), key=natural_key)
            if len(names) < len(listed):      # the legacy page showed these as broken images
                ctx.log(f"[{g.page}] {src.served}: {len(listed) - len(names)} broken link(s) skipped")
            items: dict[str, dict] = {}
            for n in names:
                base, role = self._split(src, g, n)
                it = items.setdefault(base, {"src": src, "local": local, "files": {}})
                if role in it["files"]:
                    ctx.log(f"[{g.page}] {n}: role {role!r} of {base!r} already set; skipped")
                    continue
                it["files"][role] = n
            for base, it in items.items():
                first = it["files"].get(g.role[0]) or it["files"].get("full") or next(iter(it["files"].values()))
                tags = {"dir": src.label} if multi else {}
                for lg in src.legacy:
                    if lg.subset:
                        tags[facet_key(lg)] = "yes" if rxs[lg].search(first) else "no"
                for prx in src.parse:
                    m = re.search(prx, first)
                    if m:
                        tags.update({k: v for k, v in m.groupdict().items() if v})
                it.update(id=f"{src.label}/{base}" if multi else base, base=base, first=first, tags=tags)
                rows.append(it)
        if not rows:
            raise ValueError(f"{g.page}: no legacy-matching image in {[s.served for s in g.sources]}")
        # fixture mode: round-robin over the legacy-page selections so every preset keeps items
        rows = _take(rows, ctx.limit, lambda r: tuple(sorted((k, v) for k, v in r["tags"].items()
                                                             if k == "dir" or k.startswith("g_"))))
        # thumbs: the roles differ in size and an ImageItem has one w/h (module docstring)
        sizes = {} if g.sources[0].kind == "thumbs" else self._sizes(ctx, g, rows)
        order = [g.role[0]] + [k for k in ("best", "main", "alma", "log", "log_alma", "thumb", "full") if k != g.role[0]]
        labels = {**VARIANT_LABELS, g.role[0]: g.role[1], "thumb": "Thumbnail", "full": "Full resolution"}
        if g.sources[0].kind == "variant" and "_best" in g.sources[0].suffixes:
            order = ["best"] + [k for k in order if k != "best"]
        items_out = []
        for r in rows:
            url = PREFIX[vis] + r["src"].served + "/"
            wh = sizes.get(f"{r['src'].served}/{r['first']}")
            items_out.append(ImageItem(id=r["id"], roles={k: url + quote(f) for k, f in r["files"].items()},
                                       caption=g.caption.format(id=r["id"]), tags=r["tags"],
                                       w=wh[0] if wh else None, h=wh[1] if wh else None))
        used = {k for it in items_out for k in it.roles}
        roles = [(k, labels.get(k, k)) for k in order if k in used]
        values: dict[str, set] = {}
        for it in items_out:
            for k, v in it.tags.items():
                values.setdefault(k, set()).add(v)
        facets = [("dir", "Directory")] if multi else []
        spans: dict[str, list] = {}       # one g_ facet may cover the same-named page of several dirs
        for s in g.sources:
            for lg in s.legacy:
                if lg.subset:
                    spans.setdefault(facet_key(lg), []).append((s, lg))
        for k, sl in spans.items():
            s, lg = sl[0]
            if len(sl) == 1:
                facets.append((k, f"{lg.label} (legacy {Path(lg.file).name})"))
            else:
                base = re.sub(rf"\s*\({re.escape(s.label)}\)$", "", lg.label)
                facets.append((k, f"{base} (legacy {Path(lg.file).name} in {', '.join(x.label for x, _ in sl)})"))
        # a legacy page that lists no file keeps no facet (its preset is dropped below too; a stub
        # hash naming the absent facet still selects nothing)
        facets = [(k, lab) for k, lab in facets if not (k.startswith("g_") and values.get(k) == {"no"})]
        parsed = [k for s in g.sources for p in s.parse for k in re.compile(p).groupindex]
        facets += [(k, k.replace("_", " ").capitalize()) for k in dict.fromkeys(parsed)
                   if 1 <= len(values.get(k, ())) <= MAX_FACET_VALUES]
        facets = [(k, lab) for k, lab in facets if k in values]
        keep = {k for k, _ in facets}
        for it in items_out:
            it.tags = {k: v for k, v in it.tags.items() if k in keep}
        presets = []
        for s in g.sources:
            for lg in s.legacy:
                sel = preset_facets(g, s, lg)
                if sel and all(set(v) <= values.get(k, set()) for k, v in sel.items()):
                    presets.append(Preset(Path(lg.file).stem if not multi else f"{s.label}_{Path(lg.file).stem}",
                                          lg.label, "filter", {"facets": sel}))
        return ImageSetSpec(key=g.page, items=items_out, roles=roles, facets=facets,
                            presets=list({p.key: p for p in presets}.values()))

    @staticmethod
    def _split(src: Source, g: Gallery, name: str) -> tuple[str, str]:
        """(item base name, role) of a file."""
        stem = name.rsplit(".", 1)[0]
        if src.kind == "variant":
            alt = "|".join(re.escape(s) for s in src.suffixes)
            m = re.search(rf"({alt})\.png$", name, re.I)
            base = re.sub(rf"({alt})?\.png$", "", name, count=1, flags=re.I)
            return base, (m.group(1).lstrip("_").lower() if m else g.role[0])
        if src.kind == "thumbs":
            if stem.lower().endswith("_thumbnail"):
                return stem[:-len("_thumbnail")], "thumb"
            return stem, "full"
        return stem, g.role[0]

    def _sizes(self, ctx, g: Gallery, rows: list[dict]) -> dict:
        """``{served/name: [w, h]}`` from the image headers, memoised per gallery under the
        ``(path, mtime_ns, size)`` of every file read: the directory stamp alone misses a PNG
        rewritten in place (``portalkit.context._dir_stamp``)."""
        # header reads and stats are latency-bound on the network file systems (50-130 ms
        # cold), so they run in a thread pool
        paths = [os.path.join(r["local"], r["first"]) for r in rows]
        with ThreadPoolExecutor(SIZE_THREADS) as ex:
            stats = list(ex.map(os.stat, paths))

        def read():
            with ThreadPoolExecutor(SIZE_THREADS) as ex:
                sizes = list(ex.map(image_size, paths))
            return {f"{r['src'].served}/{r['first']}": list(wh) for r, wh in zip(rows, sizes) if wh is not None}
        stamp = "\n".join(f"{p}\0{st.st_mtime_ns}\0{st.st_size}" for p, st in zip(paths, stats))
        key = hashlib.sha1(stamp.encode("utf-8", "surrogateescape")).hexdigest()[:16]
        return ctx.cache.memo(f"dirgallery_sizes:{g.page}:{key}", read, inputs=sorted({r["local"] for r in rows}))

    # -- png_b (catalog-joined) -------------------------------------------------------------
    def _pngb(self, ctx, g: Gallery, vis: str):
        from astropy.table import Table
        from portalkit.spec import CatalogSpec, ColumnSpec, ImageItem, ImageSetSpec, Preset
        src = g.sources[0]
        local = os.path.join(WEB[vis], src.served)
        params = os.path.join(os.path.dirname(os.path.realpath(local)), "model_params.ecsv")
        ctx.inputs.add(local)
        if ctx.tier == "A":
            index = os.path.join(ctx.site.portal(g.portal).legacy_dir, src.legacy[0].file)
            ctx.inputs.add(index)
            from portalkit.spec import TierUnavailable
            models = _CARD.findall(Path(index).read_text(encoding="utf-8", errors="replace"))
            if not models:
                raise TierUnavailable(f"{index}: no model cards (replaced by a stub?); use tier B")
        else:
            models = [f[:-len(PNGB_SUFFIX)] for f in os.listdir(local) if f.endswith(PNGB_SUFFIX)]
        models = sorted(set(models))

        def load():
            t = Table.read(params, format="ascii.ecsv")
            want = set(models)
            return {str(r["model"]): [float(r[c]) for c in PNGB_PARAMS] for r in t if str(r["model"]) in want}
        key = hashlib.sha1("\n".join(models).encode()).hexdigest()[:16]
        par = ctx.cache.memo(f"dirgallery_pngb_params:{key}", load, inputs=[params])
        nan = [float("nan")] * len(PNGB_PARAMS)
        models.sort(key=lambda m: (-par.get(m, nan)[0] if math.isfinite(par.get(m, nan)[0]) else math.inf, m))
        if ctx.limit is not None:
            miss = [m for m in models if m not in par]
            models = (miss + [m for m in models if m in par])[:ctx.limit]
            models.sort(key=lambda m: (-par.get(m, nan)[0] if math.isfinite(par.get(m, nan)[0]) else math.inf, m))
        url = PREFIX[vis] + src.served + "/"
        cols = {c: [math.log10(par[m][i]) if m in par and par[m][i] > 0 else float("nan") for m in models]
                for i, c in enumerate(PNGB_PARAMS)}
        t = Table({"id": models, **cols})
        bins = ((1, "< 10"), (2, "10-100"), (3, "100-10³"), (4, "10³-10⁴"), (99, "> 10⁴"))
        items = []
        for k, m in enumerate(models):
            L, Md, Me, _, Ts, Ro = par.get(m, nan)
            cap = (f"{m}: L={_fmt(L, '.0f')} L☉ · T*={_fmt(Ts, '.0f')} K · Mdisk={_fmt(Md, '.1e')} · "
                   f"Menv={_fmt(Me, '.2f')} M☉ · Rout={_fmt(Ro / 1e3, '.0f')}k au")
            lum = next((lab for hi, lab in bins if math.isfinite(L) and L > 0 and math.log10(L) < hi), "missing")
            wh = image_size(os.path.join(local, m + PNGB_SUFFIX)) if k < 1 else None
            items.append(ImageItem(id=m, roles={"image": url + quote(m + PNGB_SUFFIX)}, caption=cap,
                                   tags={"lum": lum, "params": "yes" if m in par else "missing"},
                                   w=wh[0] if wh else None, h=wh[1] if wh else None))
        if items and items[0].w:                  # one panel layout for every model
            for it in items[1:]:
                it.w, it.h = items[0].w, items[0].h
        columns = [ColumnSpec("id", "id")] + [
            ColumnSpec(c, "value", label=f"log10 {PNGB_LABELS[c][0]}", unit=PNGB_LABELS[c][1], group="params",
                       note="missing where model_params.ecsv has no value") for c in PNGB_PARAMS]
        pre = [Preset("lum3", "L > 10³ L☉", "filter", {"filters": {"ranges": {"L": [3, 99]}}}),
               Preset("lm", "L vs M_env", "axes", {"x": "Menv", "y": "L"})]
        cat = CatalogSpec(key="pngb", table=t, id="id", columns=columns, presets=pre,
                          title=f"Imaging-run models, png_b ({len(t):,})",
                          caveats=["Hyperion images at d = 5 kpc; parameters from imaging_run/model_params.ecsv."])
        lum_vals = [lab for _, lab in bins] + ["missing"]
        present = {it.tags["lum"] for it in items}
        img = ImageSetSpec(key=g.page, items=items, roles=[g.role],
                           facets=[("lum", "Luminosity [L☉]"), ("params", "Parameters in model_params.ecsv")],
                           catalog="pngb", noun=("model", "models"),
                           presets=[Preset(f"lum_{i}", f"L {lab} L☉", "filter", {"facets": {"lum": [lab]}})
                                    for i, lab in enumerate(lum_vals) if lab in present and lab != "missing"])
        return img, cat

