def _region_levels(reg) -> list[str]:
    """Levels of the ``reg`` category: by source count (descending, ties by name) so the most
    populous regions take the distinct GPU colours, :data:`REG_NONE` last. The legacy
    colours.html (colour by region) listed every region and cycled its palette."""
    n = collections.Counter(reg)
    lv = sorted((k for k in n if k != REG_NONE), key=lambda k: (-n[k], k))
    return lv + ([REG_NONE] if REG_NONE in n else [])


def _arr(v) -> np.ndarray:
    return np.array([np.nan if x is None else float(x) for x in v], dtype=float)


def _mkey(short: str) -> str:
    """NIRCam short name -> catalog column key (``F162M`` -> ``f162m``)."""
    return short.lower()


def _new_key(k: str) -> str:
    """Legacy manifold dim key -> unified key (``m_F162M`` -> ``f162m``, ``c_A_B`` -> ``a-b``)."""
    if k.startswith("m_"):
        return _mkey(k[2:])
    if k.startswith("c_"):
        a, b = k[2:].split("_")
        return f"{_mkey(a)}-{_mkey(b)}"
    return POS_KEYS.get(k, k)


def legacy_dim_alias(legacy_keys, unified) -> dict[str, str]:
    """``page.legacy.dim_alias`` of the manifold page: every legacy manifold dim key whose
    unified key differs and is a dim of the catalog (``m_F162M`` -> ``f162m``,
    ``c_F162M_F210M`` -> ``f162m-f210m``, ``ra`` -> ``ra_deg``)."""
    have = set(unified)
    out = {}
    for k in legacy_keys:
        k = str(k)
        if k.startswith("c_") and k[2:].count("_") != 1:
            continue
        nk = _new_key(k)
        if nk != k and nk in have:
            out[k] = nk
    return out


def _slug(name: str, taken: set) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "layer"
    k, i = s, 2
    while k in taken:
        k, i = f"{s}_{i}", i + 1
    taken.add(k)
    return k


# -- legacy HTML parsers (Tier A reads the served pages, Tier B the portal_pages templates) -----
def parse_hips(text: str) -> dict:
    """Base menu, Planck overlay and all-sky view of the legacy map page / MAP_TEMPLATE."""
    base = [(html_text(lab), val, bool(sel)) for val, sel, lab in
            re.findall(r'<option value="(CDS/[^"]+)"(\s+selected)?>([^<]+)</option>', text)]
    ov = re.search(r"(\w+)\s*=\s*aladin\.createImageSurvey\('([^']+)',\s*'([^']+)',\s*'(https?://[^']+)'", text)
    if not base or not ov:
        raise ValueError("legacy map page: base-layer menu or overlay survey not found")
    op = re.search(re.escape(ov.group(1)) + r"\.setOpacity\(([0-9.]+)\)", text)
    tg = re.search(r"gotoRaDec\(([-0-9.]+),\s*([-0-9.]+)\);\s*aladin\.setFoV\(([0-9.]+)\)", text)
    if not op or not tg:
        raise ValueError("legacy map page: overlay opacity or all-sky view not found")
    return {"base": base, "overlay": (ov.group(3), ov.group(4), float(op.group(1))),
            "target": tuple(float(x) for x in tg.groups())}


def parse_origins(text: str) -> dict:
    """``ORIGIN`` sample descriptions of the legacy index page / INDEX_TEMPLATE."""
    m = re.search(r"const ORIGIN=\{(.*?)\};", text, re.S)
    if not m:
        raise ValueError("legacy index page: ORIGIN table not found")
    return {k: html_text(v) for k, v in re.findall(r"(\w+):'([^']*)'", m.group(1))}


def parse_tiles(text: str) -> list[dict]:
    """Landing tiles ``{href, title, text}`` of the legacy index page / INDEX_TEMPLATE."""
    out = []
    for href, h2, p in re.findall(r'<a class="tile" href="([^"]+)"><div class="card">\s*<h2>(.*?)</h2>\s*<p>(.*?)</p>',
                                  text, re.S):
        out.append({"href": href, "title": html_text(h2).rstrip(" →").strip(), "text": html_text(p)})
    if not out:
        raise ValueError("legacy index page: no tiles found")
    return out


def html_text(s: str) -> str:
    """Tags stripped, entities decoded, whitespace collapsed."""
    return re.sub(r"\s+", " ", _html.unescape(re.sub(r"<[^>]+>", "", s))).strip()


def band_key(band: str) -> str:
    """Legacy SED band (``IRAC_3.6``, ``Herschel_250 (extended)``) -> column key (``irac_3_6``)."""
    b = band[:-len(EXT_SUFFIX)] if band.endswith(EXT_SUFFIX) else band
    return re.sub(r"[^a-z0-9]+", "_", b.lower()).strip("_")


#: lower-limit arrow in colour units: shaft length and head (x, y) size
ARROW = (0.4, 0.12, 0.05)


def limit_arrow(x: float, y: float, sign: float = 1.0) -> list[list[float]]:
    """A lower limit in x as a polyline arrow from (x, y) toward +x (``sign=-1``: toward -x)."""
    L, hx, hy = sign * ARROW[0], sign * ARROW[1], ARROW[2]
    tip = round(x + L, 6)
    return [[x, y], [tip, y], [round(tip - hx, 6), round(y + hy, 6)], [tip, y], [round(tip - hx, 6), round(y - hy, 6)]]


def cutout_url(survey: str, ra: float, dec: float, fov: float) -> str:
    q = {"hips": survey, "width": CUTOUT_PX, "height": CUTOUT_PX, "fov": round(float(fov), 5),
         "projection": "TAN", "coordsys": "icrs", "ra": round(float(ra), 6), "dec": round(float(dec), 6),
         "format": "jpg"}
    return f"{HIPS2FITS}?{urlencode(q)}"


