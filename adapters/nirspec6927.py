    def _hips(self, raw):
        from portalkit.spec import HipsSpec
        taken: set = set()
        base = []
        for nm, url, default in raw["surveys"]:
            s = re.sub(r"[^a-z0-9]+", "_", nm.lower()).strip("_") or "layer"
            k, i = s, 2
            while k in taken:
                k, i = f"{s}_{i}", i + 1
            taken.add(k)
            base.append({"id": k, "name": nm, "url": CDS_HIPS.get(url, url), "default": bool(default)})
        ra = np.array([r["RA"] for r in raw["rows"]], float)
        dec = np.array([r["Dec"] for r in raw["rows"]], float)
        if not ra.size:
            return HipsSpec(base=base)
        c = [float(ra.mean()), float(dec.mean())]                  # AladinMap.write_html
        span = max((ra.max() - ra.min()) * np.cos(np.radians(c[1])), dec.max() - dec.min())
        return HipsSpec(base=base, target={"ra": c[0], "dec": c[1], "fov": float(max(0.03, 1.6 * span))})

