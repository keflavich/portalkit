def test_stub_html_content_and_escaping():
    s = bmod.stub_html("unified/map.html", "ccd")
    assert len(s.encode()) < 400
    assert "location.replace('unified/map.html'+location.search+(location.hash||'#ccd'))" in s
    assert '<a href="unified/map.html#ccd">' in s
    evil = bmod.stub_html("x'</script><b>.html", "#p")
    assert "</script><b>" not in evil.split("</script>", 1)[0]
    assert "\\'" in evil and "&lt;/script&gt;" in evil
    assert "location.hash||'')" in bmod.stub_html("a.html")


def test_replace_stub_backup_and_manifest(world):
    res = run(world)
    old = world["legacy"] / "old_map.html"
    stub = old.read_text()
    assert stub == bmod.stub_html("unified/map.html", "ccd")
    bak = world["legacy"] / ".portalkit_backup" / BID / "old_map.html"
    assert bak.read_text() == LEGACY
    assert bak.stat().st_mtime == pytest.approx(1.6e9)
    doc = bmod.read_backup(world["legacy"], BID)
    assert bmod.validate_backup(doc) == []
    rec = doc["files"][0]
    assert rec["md5"] == dmod.md5_file(bak) and rec["size"] == len(LEGACY)
    assert rec["page"] == "map" and rec["unified"] == "unified/map.html"
    assert rec["written_sha256"] == dmod.sha256_file(old)[0]
    man = manifest(world)
    assert schema.validate_deploy(man) == []
    assert man["replaced"] == [{"legacy": "../old_map.html",
                                "backup": f".portalkit_backup/{BID}/old_map.html",
                                "md5": rec["md5"], "mode": "stub", "size": len(LEGACY),
                                "build_id": BID}]
    assert man["builds"][-1]["replace"] == "stub"
    assert [r["legacy"] for r in res.replaced] == ["../old_map.html"]
    # a page that was not built keeps its legacy files, with a warning
    assert any("page 'cat' was not built" in w for w in res.plan.warnings)


def test_missing_legacy_file_warns(world):
    d = world["stage"] / FAM / BID / "main"
    (d / "cat.html").write_text("<p>catalog</p>")
    res = run(world)
    assert any("old_cat.html is missing" in w for w in res.plan.warnings)
    assert not (world["legacy"] / "old_cat.html").exists()


def test_rollback_restores_and_updates_manifest(world):
    run(world)
    old = world["legacy"] / "old_map.html"
    dry = bmod.rollback(world["legacy"], BID, target=world["target"], dry_run=True)
    assert dry.restored == ["old_map.html"] and old.read_text() != LEGACY
    res = bmod.rollback(world["legacy"], BID, target=world["target"], family=FAM,
                        portal_id="main")
    assert res.restored == ["old_map.html"] and res.manifest_updated
    assert old.read_text() == LEGACY
    assert old.stat().st_mtime == pytest.approx(1.6e9)
    man = manifest(world)
    assert schema.validate_deploy(man) == []
    assert man["replaced"] == []
    assert man["builds"][-1]["note"].startswith("replace rolled back")
    # only the replace is undone: the unified files stay served, the build stays deployed
    assert dmod.deployed_builds(man) == [BID]
    assert (world["target"] / "map.html").is_file()
    assert "rolled_back" in bmod.read_backup(world["legacy"], BID)
    again = bmod.rollback(world["legacy"], BID, target=world["target"])
    assert again.skipped == ["old_map.html"] and again.restored == []


def test_rollback_refuses_edited_stub(world):
    run(world)
    old = world["legacy"] / "old_map.html"
    old.write_text("someone regenerated the legacy page")
    with pytest.raises(OwnershipConflict) as ei:
        bmod.rollback(world["legacy"], BID, target=world["target"])
    assert ei.value.exit_code == 4
    assert old.read_text() == "someone regenerated the legacy page"
    bmod.rollback(world["legacy"], BID, target=world["target"], force=True)
    assert old.read_text() == LEGACY


def test_rollback_refuses_corrupt_backup(world):
    run(world)
    bak = world["legacy"] / ".portalkit_backup" / BID / "old_map.html"
    bak.write_text("bit rot")
    old = world["legacy"] / "old_map.html"
    stub = old.read_text()
    with pytest.raises(VerifyFailure) as ei:
        bmod.rollback(world["legacy"], BID, target=world["target"])
    assert ei.value.exit_code == 1
    assert old.read_text() == stub
    bak.unlink()
    with pytest.raises(VerifyFailure):
        bmod.rollback(world["legacy"], BID, target=world["target"])


def test_rollback_without_backup(world):
    with pytest.raises(UsageError):
        bmod.rollback(world["legacy"], BID)
    bdir = world["legacy"] / ".portalkit_backup" / BID
    bdir.mkdir(parents=True)
    (bdir / "backup.json").write_text('{"schema": "pk-backup/1"}')
    with pytest.raises(DeployError):
        bmod.rollback(world["legacy"], BID)


def test_same_build_redeploy_keeps_original_backup(world):
    run(world)
    run(world)
    bak = world["legacy"] / ".portalkit_backup" / BID / "old_map.html"
    assert bak.read_text() == LEGACY
    assert len(bmod.read_backup(world["legacy"], BID)["files"]) == 1
    assert len(manifest(world)["replaced"]) == 1


def test_two_builds_roll_back_in_order(world):
    run(world)
    stub1 = (world["legacy"] / "old_map.html").read_text()
    stage_portal(world["stage"], BID2, "v2")
    run(world, site(world, preset=""), bid=BID2)
    assert bmod.list_backups(world["legacy"]) == [BID, BID2]
    assert (world["legacy"] / ".portalkit_backup" / BID2 / "old_map.html").read_text() == stub1
    assert len(manifest(world)["replaced"]) == 2
    bmod.rollback(world["legacy"], BID2, target=world["target"])
    assert (world["legacy"] / "old_map.html").read_text() == stub1
    assert [r["build_id"] for r in manifest(world)["replaced"]] == [BID]
    bmod.rollback(world["legacy"], BID, target=world["target"])
    assert (world["legacy"] / "old_map.html").read_text() == LEGACY


