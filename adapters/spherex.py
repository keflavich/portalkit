def _jsn(v) -> str:
    """A number as a JavaScript template literal prints it (``6.0`` -> ``6``, None -> ``null``)."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def _tofixed(x: float, nd: int) -> str:
    """JavaScript ``Number.prototype.toFixed``: the exact binary value rounded half away from
    zero (Python's format rounds half to even, so 48.5 -> '48' where toFixed gives '49')."""
    x = float(x)
    if not math.isfinite(x):
        return "NaN" if math.isnan(x) else ("Infinity" if x > 0 else "-Infinity")
    if abs(x) >= 1e21:
        return repr(x)                            # toFixed falls back to String(x): '1e+21'
    if x == 0:
        x = 0.0                                   # (-0).toFixed() has no sign; (-0.4).toFixed(0) is '-0'
    q = decimal.Decimal(x).quantize(decimal.Decimal(1).scaleb(-nd), rounding=decimal.ROUND_HALF_UP)
    return f"{q:f}"


def _pct(v) -> str:
    """legacy ``pct``: ``(100*v).toFixed(0)+'%'``, an em dash for null."""
    return "—" if v is None else f"{_tofixed(100 * float(v), 0)}%"


def _regions(sources: list[dict]) -> list[dict]:
    """Go-to regions of portal_pages.render_map (portal_pages.py:798-830): sources grouped by
    region label (or sample), groups of >= 3, unit-vector mean centre, fov = max(0.5, 1.6 span)."""
    groups: dict[str, list] = {}
    for r in sources:
        if r.get("ra") is None:
            continue
        groups.setdefault((r.get("reg") or "").strip() or r["s"], []).append(r)
    out = []
    for name, rows in groups.items():
        if len(rows) < 3:
            continue
        ra = np.array([x["ra"] for x in rows], dtype=float)
        dec = np.array([x["dec"] for x in rows], dtype=float)
        rr, dd = np.radians(ra), np.radians(dec)
        v = np.array([np.cos(dd) * np.cos(rr), np.cos(dd) * np.sin(rr), np.sin(dd)]).mean(axis=1)
        cdec = np.degrees(np.arcsin(v[2] / np.linalg.norm(v)))
        cra = np.degrees(np.arctan2(v[1], v[0])) % 360
        span = max(float(dec.max() - dec.min()), float((ra.max() - ra.min()) * np.cos(np.radians(cdec))))
        out.append(dict(name=name, n=len(rows), ra=round(cra, 5), dec=round(cdec, 5),
                        fov=round(max(0.5, span * 1.6), 3)))
    out.sort(key=lambda r: -r["n"])
    return out


def sed_notes(d: dict) -> str:
    """The legacy sed.html confusion notes (portal_pages.py SED_TEMPLATE ``notes``) as text."""
    notes = []
    p = d.get("p") or []
    if str(d.get("fq", "")).startswith("confused"):
        notes.append(f"Neighbours hold {_pct(d.get('cf60'))} of the 22 µm flux within 60″. "
                     "IRAS beams are 0.75′×4.5′ at 12 µm and 3′×5′ at 100 µm, "
                     "so the IRAS points here are an upper envelope on the star, not its flux.")
    if d.get("c2") is not None and d["c2"] >= 6:
        notes.append(f"IRAS cirr2 = {_jsn(d['c2'])} on a 1–9 scale, with the 100 µm sky at "
                     f"{_jsn(d.get('c3'))} MJy/sr: the cirrus is comparable to the source, so read the 60 and "
                     "100 µm points as the star plus its foreground.")
    ext = [q for q in p if str(q[4]).endswith("(extended)")]
    if ext:
        notes.append(f"The Herschel catalogue flags {', '.join(_jsn(q[0]) + ' µm' for q in ext)} "
                     "as extended, so that emission belongs to a cloud in the beam rather than to the star.")
    h100 = next((q for q in p if q[3] == "Herschel" and q[0] == 100), None)
    i100 = next((q for q in p if str(q[3]).startswith("IRAS") and q[0] == 100), None)
    if h100 and i100 and h100[1] < 0.7 * i100[1]:
        notes.append(f"Herschel 100 µm is {_tofixed(i100[1] / h100[1], 1)}× below IRAS 100 µm. "
                     "PACS and SPIRE fluxes here are point-source fits, so emission spread beyond "
                     "the PSF — a resolved shell, or cirrus inside the IRAS beam — separates the two.")
    if d.get("hprog"):
        notes.append(f"Herschel programs: {d['hprog']}.")
    if d.get("aprog"):
        notes.append(f"ALMA projects: {d['aprog']}.")
    return " ".join(notes)
