"""JWST NIRSpec program 6927 (Brick MSA survey) family adapter (WP22; ARCHITECTURE.md
sections 9 and 14.7, wave 1).

Legacy portal: ``/orange/adamginsburg/jwst/spectra/nirspec_6927`` (secure), generated by the
``NIRSpec_6927_*.py`` scripts in ``/orange/adamginsburg/jwst/brick/analysis``.

* Tier A reads legacy payloads: the arrays embedded in the legacy HTML (``srcdata``,
  ``SURVEYS``, manifold ``DATA``, ice ``ROWS``/``PAIRS``, colour-colour and PV/SED
  ``SOURCES``, CO-gas ``ROWS``, ``BANDS``/``ICEMARKS``) and the ``specdata/<name>.json``
  spectra. Deliberate deviation from section 9.2 (Tier A runs no science code): the legacy
  portal has no 2D-spectrum, background-catalogue or isochrone payload, so every tier stitches
  the s2d products the legacy map lists, reads the Brick catalogue for the density background
  and interpolates MIST tracks. The parity oracle covers everything else.
* Tier B imports ``NIRSpec_6927_AladinMap`` (``collect_sources``/``attach_figures``/
  ``SURVEYS``), ``NIRSpec_6927_Manifold`` (``build``/``standardize``/``pca_frame``),
  ``NIRSpec_6927_IceColumns`` (``build_rows``/``attach_global``) and
  ``NIRSpec_6927_SEDGallery`` (``index_sed_figures``), reads the ECSV tables written by the
  pipeline and the x1d/s2d FITS products (cached per source through ``ctx.cache``).

Record loaders are closures over the per-call data, so the module-level ``ADAPTER`` can serve
several ``datasets()`` calls (tiers, limits) in one process.

Fixed legacy bugs: the stem regex no longer crashes on unparseable PNG names (they are
skipped), stale PNGs of superseded reductions are dropped, empty ice pairs get no preset, and
hash writes are left to the shared hash module (written on change only).
"""

