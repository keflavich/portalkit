    def _ccd(self, raw, sel, src_ids: set, sed_ids: set):
        from astropy.table import Table
        from portalkit.spec import CatalogSpec, ColumnSpec, DensitySpec, Preset, VirtualDim
        j, rows = raw["ccd"], raw["ccd_rows"][sel]
        ids = np.array([f"WD2-{int(r):06d}" for r in rows])
        t = Table({"id": ids, "ra": np.asarray(j["R"], float)[sel], "dec": np.asarray(j["D"], float)[sel]})
        yso = np.isin(sel, np.asarray(j["SAR"], dtype=np.int64))
        t["yso"] = np.where(yso, "Sabbi+2020 YSO", "other")
        t["in_src"] = np.isin(ids, sorted(src_ids))
        t["has_sed"] = np.isin(ids, sorted(sed_ids))
        cols = [ColumnSpec("id", "id"), ColumnSpec("yso", "category", label="Sabbi+2020 YSO match",
                                                   levels=["Sabbi+2020 YSO", "other"],
                                                   colors={"Sabbi+2020 YSO": "#ff8ac4", "other": "#67d5b5"}),
                ColumnSpec("in_src", "flag", label="In the manifold catalogue",
                           note="the manifold / colour-colour links resolve for these rows"),
                ColumnSpec("has_sed", "flag", label="Has an SED fit", note="the SED gallery link resolves")]
        keys = {}
        for f in j["F"]:
            k = keys[f] = f if _fid(f) else f"hst_{f}"
            m, q = np.asarray(j["M"][f], float)[sel], np.asarray(j["Q"][f], float)[sel]
            t[k] = np.where(m != 0, m / 100.0, np.nan)
            t[f"sn_{f}"] = np.where(m != 0, q, np.nan)
            hst = not _fid(f)
            cols += [ColumnSpec(k, "mag", label=f"HST {f.upper() if f != 'im' else 'Im'} (Sabbi+2020)" if hst
                                else f.upper(), unit="mag (Vega)", filter=_fid(f), step=0.01, invert=True,
                                group="hst" if hst else "jwst"),
                     ColumnSpec(f"sn_{f}", "value", label=f"S/N {f.upper()}", group="snr", step=1,
                                note=f"ceil(S/N) - 1, capped at {max(j['snr_choices'])}; S/N > T is this >= T")]
        cmd = (f"{keys[j['cmd'][0]]}-{keys[j['cmd'][1]]}", keys[j["cmd"][2]])
        ccd = (f"{keys[j['ccd'][0]]}-{keys[j['ccd'][1]]}", f"{keys[j['ccd'][2]]}-{keys[j['ccd'][3]]}")
        fk = list(keys.values())
        virt = [VirtualDim(f"{a}-{b}", label=f"{a.upper()} - {b.upper()}", unit="mag", group="colors")
                for i, a in enumerate(fk) for b in fk[i + 1:]]
        pre = [Preset("cmd", "CMD", "axes", {"x": cmd[0], "y": cmd[1]}),
               Preset("ccd", "CCD", "axes", {"x": ccd[0], "y": ccd[1]})]
        # legacy: each diagram keeps rows with S/N > T in the filters it uses. Filters act on the
        # whole dataset, so snr<T> cuts on both diagrams' filters and snr<T>_cmd / _ccd on one.
        for s in j["snr_choices"]:
            for sfx, fs, lab in (("", j["cmd"] + j["ccd"], "S/N > {} (CMD + CCD filters)"),
                                 ("_cmd", j["cmd"], "CMD S/N > {}"), ("_ccd", j["ccd"], "CCD S/N > {}")):
                if sfx and s == min(j["snr_choices"]):
                    continue      # the S/N > min floor is the catalogue cut itself
                pre.append(Preset(f"snr{s}{sfx}", lab.format(s), "filter",
                                  {"filters": {"ranges": {f"sn_{f}": [s, 1000] for f in sorted(set(fs))}}}))
        if yso.any():
            pre.append(Preset("sabbi_yso", "Sabbi+2020 YSO candidates", "selection", {"sel": _sel(ids[yso], "ccd")}))
        dens = [DensitySpec(k, x, y, xr=_pct(self._expr(t, x)), yr=_pct(self._expr(t, y)))
                for k, (x, y) in (("cmd", cmd), ("ccd", ccd))]
        return CatalogSpec(key="ccd", table=t, id="id", columns=cols, ra="ra", dec="dec", virtual=virt,
                           presets=pre, density=dens, title=f"Wd2 NIRCam catalogue, S/N > {min(j['snr_choices'])} "
                           f"in >= 2 filters ({len(t):,} of {int(j['n_all']):,} rows)",
                           caveats=[f"Magnitudes are kept where S/N > {min(j['snr_choices'])} (0.01 mag legacy "
                                    "precision); the S/N columns hold the legacy integer S/N floor.",
                                    "HST Im/V/H/J are Sabbi+2020 photometry chained through the EWOCS "
                                    "catalogue; they carry no filter curve.",
                                    f"The legacy {int(j['topn']):,}-point cap per diagram is replaced by "
                                    "density rendering of every row.",
                                    f"The page opens with S/N > {int(j['snr'])} in every CMD and CCD filter "
                                    "(both diagrams show the same rows). The legacy page cut each diagram on "
                                    "its own filters only; the 'CMD S/N' and 'CCD S/N' chips give that cut "
                                    "for one diagram.",
                                    f"{int(np.sum(t['in_src'])):,} rows are in the manifold catalogue and "
                                    f"{int(np.sum(t['has_sed'])):,} have an SED fit; the manifold and SED "
                                    "gallery links resolve only for those rows."])

    def _seds(self, raw, sel, pos):
        from astropy.table import Table
        from portalkit.spec import CatalogSpec, ColumnSpec, Preset, VirtualDim
        s = raw["sed"][sel]
        names = [str(n) for n in s["name"]]
        T, edge = np.asarray(s["bb_T"], float), np.asarray(s["bb_at_edge"], bool)
        t = Table({"id": names, "ra": np.asarray(s["ra"], float), "dec": np.asarray(s["dec"], float),
                   "fit": np.where(~np.isfinite(T), "no fit", np.where(edge, "at grid edge", "BB fit"))})
        cols = [ColumnSpec("id", "id"), ColumnSpec("fit", "category", label="Blackbody fit",
                                                   levels=["BB fit", "at grid edge", "no fit"])]
        for k, lab, unit in (("bb_T", "BB temperature", "K"), ("bb_av", "BB A_V", "mag"),
                             ("bb_chi2_red", "BB reduced chi2", ""), ("n_filt_independent", "Filters detected", ""),
                             ("n_measured", "Filters measured", "")):
            t[k] = np.asarray(s[k], float)
            cols.append(ColumnSpec(k, "value", label=lab, unit=unit, group="fit"))
        idx = np.array([pos[n] for n in names], dtype=np.int64)
        mags = [d for d in raw["mani"]["dims"] if _fid(d["key"])]
        for d in mags:
            t[d["key"]] = np.round(np.array(d["v"], dtype=float)[idx], 3)
            cols.append(ColumnSpec(d["key"], "mag", label=d["label"], unit=d["unit"], filter=_fid(d["key"]),
                                   step=0.001, group="phot", invert=True))
        cmd = ("m_f182m-m_f410m", "m_f410m")
        self._minfilt = int(np.nanmin(np.asarray(raw["sed"]["n_filt_independent"], float)))
        self._nfilt = len(mags)
        return CatalogSpec(key="seds", table=t, id="id", columns=cols, ra="ra", dec="dec",
                           virtual=[VirtualDim(cmd[0], label="F182M - F410M", unit="mag (Vega)", group="phot")],
                           presets=[Preset("cmd", "CMD", "axes", {"x": cmd[0], "y": cmd[1]}),
                                    Preset("bbfit", "BB fit inside the grid", "filter",   # cats = levels off
                                           {"filters": {"cats": {"fit": ["at grid edge", "no fit"]}}})],
                           title=f"Wd2 SED fits ({len(t):,} stars)",
                           caveats=["Single-blackbody fits with a G23 extinction term; the curve is a shape "
                                    "guide. 'at grid edge' marks fits that hit the temperature or A_V limit."])

    def _img(self, seds, catalog, src=None):
        from portalkit.spec import ImageItem, ImageSetSpec
        t = seds.table
        have = None if src is None else {str(x) for x in src.table["id"]}
        items = [ImageItem(id=str(n), roles={"sed": f"{PNG_URL}{n}.png"},
                           caption=f"{n}  ({int(f)}/{self._nfilt} filters, {ra:.5f} {dec:.5f})")
                 for n, f, ra, dec in zip(t["id"], t["n_filt_independent"], t["ra"], t["dec"])
                 if have is None or str(n) in have]
        return ImageSetSpec(key="sedimg" if src is None else "sedfig", items=items,
                            roles=[("sed", "SED fit (static PNG)")], catalog=catalog)

    def _hips(self, raw):
        from portalkit.spec import HipsSpec
        taken: set = set()
        base = [{"id": _slug(n, taken), "name": n, "url": u, "default": i == 0}
                for i, (n, u) in enumerate(raw["bases"])]
        seen = {u for _, u in raw["bases"]} | {u for _, u in raw["overlays"]}
        ovl = [list(o) for o in raw["overlays"]] + [s for s in raw["surveys"] if s[1] not in seen]
        rungs = []
        for tag, d, label, desc in raw["rungs"]:
            um = [float(x) for x in re.findall(r"([\d.]+)\s*μm", label)]
            rungs.append({"id": f"w{tag}", "label": label, "url": f"{AVM}{d.strip('/')}/", "desc": desc,
                          **(dict(zip(("r_um", "g_um", "b_um"), um)) if len(um) == 3 else {})})
        c = raw["center"]
        return HipsSpec(base=base, rungs=rungs,
                        overlays=[{"id": _slug(n, taken), "name": n, "url": u, "opacity": 1.0, "default": False}
                                  for n, u in ovl],
                        target={"ra": float(c[0]), "dec": float(c[1]), "fov": float(raw["fov"])})

    def _iso(self, ctx, raw):
        from portalkit.physics.isochrones import DEFAULT_MIST, build_isochrone_track
        from portalkit.spec import IsochroneSpec, Track
        age, dist = raw["iso"]
        filters = [_fid(d["key"]) for d in raw["mani"]["dims"] if _fid(d["key"])]

        def load():
            tr = build_isochrone_track(DEFAULT_MIST, age_log10_yr=age, dist_pc=dist, filters=filters,
                                       label=f"MIST {10 ** age / 1e6:.1f} Myr, {dist / 1000:.2f} kpc")
            return {"label": tr.label, "age_myr": tr.age_myr, "dist_pc": tr.dist_pc, "feh": tr.feh,
                    "mass": np.asarray(tr.mass).tolist(),
                    "mags": {k: [None if not np.isfinite(v) else float(v) for v in m] for k, m in tr.mags.items()}}
        d = ctx.cache.memo(f"wd2_iso_v1_{age:.3f}_{dist:.0f}_{len(filters)}", load, inputs=[DEFAULT_MIST])
        return IsochroneSpec(tracks=[Track(d["label"], d["age_myr"], d["dist_pc"], d["feh"],
                                           np.asarray(d["mass"], float),
                                           {k: np.array([np.nan if v is None else v for v in m], float)
                                            for k, m in d["mags"].items()})])

