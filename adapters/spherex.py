"""SPHEREx colour portal adapter (WP27; ARCHITECTURE.md sections 9 and 14.9).

Legacy portal ``web/public/spherex/portal`` (index, colours, browse, map, sed and
spherex_manifold), generated by ``SPHEREx_ColorPortal.py``, ``portal_pages.py`` and
``SPHEREx_Portal_Manifold.py`` in ``/orange/adamginsburg/spherex`` and deployed with
``deploy_portal.sh`` (rsync). The unified portal replaces that rsync with ``portalkit deploy``.

* One shared catalog bundle (``src``, 2442 sources in the full build) feeds the six pages. The
  legacy pages embedded the catalog four times (colours, browse, map and the manifold's regex
  scrape of colours.html, about 3.3 MB in all).
* Spectra (``spectra/<i>.json``, µJy) become one pks1 record set in shards, converted to Jy, with
  SPHEREx and the matched Spitzer IRS spectrum as two segments (the IRS segment is not rescaled).
  The spectrum1d pane replaces the legacy hand-written SVG views. Those views shared a
  one-shot shift-drag pan (SPHEREx_ColorPortal.py:1500-1572, portal_pages.py:391-392 and
  1201-1202).
* The far-infrared SED page reads ``seds`` (one row per R CrB / HdC star): photometry as flux
  columns in µJy with errors, the legacy filter chips as flags and the confusion notes as a
  text column. The SPHEREx/IRS spectrum joins the SED as a ``sedcurve`` record set (``sedspec``)
  and, keyed to ``seds``, as the pks1 set ``sedpks`` of a spectrum1d pane in SED mode: that pane
  draws the photometry with the spectrum and keeps the legacy view's zoom, pan and 0.7-40 um
  button. The sed page has no per-id links to the src pages (143 of the 316 SED stars have no
  SPHEREx spectrum, so no src row).
* The sky map's HiPS list, Planck 857 GHz overlay (opacity 0.5) and its go-to regions become a
  ``HipsSpec`` with bookmarks. The Yoo W51 populations, the 26 YooW51red lower limits (as
  right-pointing arrows) and the divider become dim-space overlay layers on the F162M-F210M vs
  F360M-F480M diagram.
* Legacy links: the manifold's kv-view hash names legacy dim keys (``x=m_F162M``,
  ``c_F162M_F210M``); :func:`legacy_dim_alias` maps them onto the unified keys
  (``page.legacy.dim_alias``). colours.html kept its state in the query string, read by the
  ``spherex-colours`` grammar (sites/spherex.toml), whose default lower-cased names match the
  unified keys. Its colour-by choices (s, q, cls, reg) are all category columns; ``reg``
  (region) keeps every legacy region as a level, ordered by source count (:func:`_region_levels`),
  so ``?c=reg&hide=<region>`` links resolve.
* ``index.html`` was hand-patched after generation (``portal_pages.INDEX_TEMPLATE`` has no such
  tile). The patch added the "Grand-tour manifold" tile and the "manifold" nav link
  (:data:`MANIFOLD_TILE`). The unified landing page carries that tile as a card.

Tier A reads only the legacy payloads embedded in the served pages. Tier B imports the legacy
modules: ``SPHEREx_Portal_Manifold.load_payload/build/build_categories/build_presets`` for the
catalog dimensions, ``SPHEREx_ColorPortal.build_seds`` for the SED records (memoised) and the
``portal_pages`` templates for the HiPS layers, sample origins and landing tiles. The go-to
regions are recomputed with the ``portal_pages.render_map`` rule (:func:`_regions`), which writes
``map.html`` itself and so cannot be called here. The ported legacy rules sit in the ``_fallback``
section at the end of the module.

Fixture builds (``ctx.limit``) keep up to ``limit`` sources: R CrB stars that have an SED record,
sources with an IRS spectrum, then the samples in turn. ``seds`` lists the SED stars in that
selection first.
"""

