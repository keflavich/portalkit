            off = [lv for lv in cat.column("obs").levels if lv != "15-16"]
            full.data["sel"] = encode_recipe([{"op": "replace", "kind": "filter", "view": {"ds": "src"},
                                               "filters": {"cats": {"obs": off}}}])
