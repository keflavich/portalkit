    # -- common intermediate -----------------------------------------------------------------
    def datasets(self, ctx):
        from portalkit.spec import ExtinctionSpec, TemplateSpec, TierUnavailable
        if ctx.tier not in self.tiers:
            raise TierUnavailable(f"spherex implements tiers A and B, not {ctx.tier}")
        raw = self._tier_a(ctx) if ctx.tier == "A" else self._tier_b(ctx)
        self._raw = raw
        sel = self.select(raw["sources"], raw["seds"], ctx.limit)
        ssel = self.select_seds(raw["seds"], {str(raw["sources"][i]["id"]) for i in sel}, ctx.limit)
        ctx.inputs.add(raw["spectra"])
        src = self._src(raw, sel)
        seds = self._seds(raw, ssel)
        tpl_path = LEGACY / TEMPLATES_JSON
        ctx.inputs.add(tpl_path)
        ds = {"src": src, "seds": seds,
              "spec": self._spec(raw, sel), "sedspec": self._sedspec(raw, ssel), "sedpks": self._sedpks(raw, ssel),
              "cut": self._cutouts("cut", "src", src.table, CUTOUTS_SRC),
              "sedcut": self._cutouts("sedcut", "seds", seds.table, CUTOUTS_SED),
              "ovl": self._overlays(ctx), "hips": self._hips(raw), "filters": self._filters(raw, seds),
              "tpl": TemplateSpec(source=tpl_path), "ext": ExtinctionSpec()}
        ds["readme"] = self._readme(ctx, raw, ds)
        return ds

    @staticmethod
    def select(sources: list[dict], seds: list[dict], limit) -> list[int]:
        """Row indices of the build: all, or a fixture of at most ``limit`` rows (SED stars,
        IRS sources, then the samples round-robin), in input order."""
        n = len(sources)
        if limit is None:
            return list(range(n))
        limit = max(0, int(limit))
        k = max(1, limit // 5)
        with_sed = {str(s["id"]) for s in seds if s.get("i") is not None}
        pick: list[int] = []
        seen: set[int] = set()

        def add(i):
            if i not in seen and len(pick) < limit:
                pick.append(i)
                seen.add(i)
        for i in [i for i, r in enumerate(sources) if str(r["id"]) in with_sed][:k]:
            add(i)
        for i in [i for i, r in enumerate(sources) if r.get("irs")][:k]:
            add(i)
        by = collections.OrderedDict()
        for i, r in enumerate(sources):
            by.setdefault(r["s"], []).append(i)
        queues = [collections.deque(v) for v in by.values()]
        while len(pick) < limit and any(queues):
            for q in queues:
                while q and q[0] in seen:
                    q.popleft()
                if q:
                    add(q.popleft())
        return sorted(pick)

    @staticmethod
    def select_seds(seds: list[dict], src_ids: set, limit) -> list[int]:
        if limit is None:
            return list(range(len(seds)))
        first = [i for i, s in enumerate(seds) if str(s["id"]) in src_ids]
        rest = [i for i, s in enumerate(seds) if str(s["id"]) not in src_ids]
        return sorted((first + rest)[:max(0, int(limit))])

    # -- src: the shared catalog ---------------------------------------------------------------
    def _src(self, raw, sel):
        from astropy.table import Table
        from portalkit.spec import CatalogSpec, ColumnSpec, Group, ManifoldSpec, Preset, VirtualDim
        rows = [raw["sources"][i] for i in sel]
        shorts, kinds, dims = raw["filters"], raw["kinds"], raw["dims"]
        fidx = {s: j for j, s in enumerate(shorts)}
        t = Table()
        t["id"] = [str(r["id"]) for r in rows]
        t["ra"] = _arr([r.get("ra") for r in rows])
        t["dec"] = _arr([r.get("dec") for r in rows])
        cols = [ColumnSpec("id", "id"),
                ColumnSpec("ra", "ra", label="RA", unit="deg"), ColumnSpec("dec", "dec", label="Dec", unit="deg")]
        cats = {c["key"]: c for c in raw["cats"]}
        for key, vals in (("s", [r["s"] for r in rows]), ("q", [r["q"] for r in rows]),
                          ("cls", [r.get("cls") or "unclassified" for r in rows])):
            t[key] = vals
            pal = cats[key]["colors"]
            present = list(dict.fromkeys(vals))
            lv = [x for x in pal if x in present] + sorted(x for x in present if x not in pal)
            cols.append(ColumnSpec(key, "category", label=cats[key]["label"], levels=lv,
                                   colors={k: v for k, v in pal.items() if k in lv}))
        t["qr"] = [str(r.get("qr") or "") for r in rows]
        cols.append(ColumnSpec("qr", "category", label="Quality reason",
                               note="why the source has its quality tier (outlier channels, undersampling)"))
        t["blended"] = ["blended" if r.get("blended") == 1 else "not blended" if r.get("blended") == 0
                        else "not assessed" for r in rows]
        cols.append(ColumnSpec("blended", "category", label="Blended", note=dims.get("blended", ("",) * 5)[4]))
        # magnitudes, grouped wide / medium / narrow
        mk = []
        for s in shorts:
            j, key = fidx[s], _mkey(s)
            v = _arr([(r.get("m") or [None] * len(shorts))[j] if j < len(r.get("m") or []) else None for r in rows])
            if not np.isfinite(v).any():
                continue
            t[key] = v
            mk.append(key)
            lab, unit, grp, _, note, _ = dims.get(f"m_{s}", (s, "mag", f"phot_{kinds[s]}", False, "", True))
            cols.append(ColumnSpec(key, "mag", label=lab, unit="mag (Vega)", filter=f"JWST/NIRCam.{s}", step=0.001,
                                   group=grp, invert=True, note=note))
        # values and flags of the legacy manifold dims
        for lk, nk in POS_KEYS.items():
            lab, unit, grp, _, note, _ = dims.get(lk, (lk.upper(), "deg", "pos", False, "", False))
            t[nk] = np.array(t[lk], dtype=float)
            cols.append(ColumnSpec(nk, "value", label=lab, unit=unit or "deg", group=grp, note=note))
        tb = [list(r.get("tb") or []) for r in rows]
        src_field = {"nch": "n"}
        vk = []
        for lk, (lab, unit, grp, log, note, flip) in dims.items():
            if lk.startswith(("m_", "c_")) or lk in ("ra", "dec") or lk in SKIP_DIMS:
                continue
            if lk == "tbcount":
                v = np.array([float(len(x)) for x in tb])
            else:
                v = _arr([r.get(src_field.get(lk, lk)) for r in rows])
            if lk in FLAG_DIMS:
                t[lk] = np.nan_to_num(v, nan=0.0) > 0
                cols.append(ColumnSpec(lk, "flag", label=lab, group=grp, note=note))
                continue
            if not np.isfinite(v).any():
                continue
            t[lk] = v
            vk.append(lk)
            cols.append(ColumnSpec(lk, "value", label=lab, unit=unit, group=grp, log=log, note=note,
                                   invert=True if flip else None))
        # COVERAGE_FRAC flags: one per filter that some source keeps truncated
        trunc = [s for s in shorts if any(s in (r.get("tb") or []) for r in raw["sources"])]
        for s in trunc:
            key = f"tb_{_mkey(s)}"
            t[key] = np.array([s in x for x in tb], dtype=bool)
            cols.append(ColumnSpec(key, "flag", label=f"{s} truncated", group="meta",
                                   note=f"the spectrum samples at least COVERAGE_FRAC but less than COVERAGE_CLEAN of "
                                        f"the {s} throughput; the magnitude is kept and reads slightly faint"))
        t["tb"] = [", ".join(x) for x in tb]
        # region: a category so the legacy colours.html colour-by 'region' links (?c=reg,
        # &hide=<region>|..) resolve to a colour-by column and a cats filter
        reg = [(r.get("reg") or "").strip() or REG_NONE for r in rows]
        t["reg"] = reg
        t["otype"] = [str(r.get("otype") or "") for r in rows]
        cols += [ColumnSpec("tb", "text", label="Truncated filters"),
                 ColumnSpec("reg", "category", label="Region", levels=_region_levels(reg),
                            note=f"levels by source count, {REG_NONE} = no region; only the most populous "
                                 "regions get distinct plot colours, the rest share the neutral colour"),
                 ColumnSpec("otype", "text", label="c2d object type")]
        have = set(mk)
        virt = []
        for lk, (lab, unit, grp, *_rest) in dims.items():
            if lk.startswith("c_"):
                a, b = lk[2:].split("_")
                if _mkey(a) in have and _mkey(b) in have:
                    virt.append(VirtualDim(_new_key(lk), label=lab, unit="mag (Vega)", group=grp))
        vkeys = [v.key for v in virt]
        pos = list(POS_KEYS.values())
        mdims = mk + vkeys + vk + pos
        gd = collections.defaultdict(list)
        for c in cols:
            if c.group and c.key in mdims:
                gd[c.group].append(c.key)
        for v in virt:
            gd[v.group].append(v.key)
        groups = [Group(g, lab, gd[g]) for g, lab in raw["groups"] if gd[g]]
        presets = []
        dset = set(mdims)
        for p in raw["presets"]:
            x = [_new_key(k) for k in p["x"]]
            y = [_new_key(k) for k in p["y"]]
            if len(x) != 1 or len(y) != 1 or not {x[0], y[0]} <= dset:
                continue
            presets.append(Preset(p["id"], p["name"], "axes",
                                  {"x": x[0], "y": y[0], "note": p.get("note", ""), "code": p.get("code", ""),
                                   **({"color": p["color"]} if p.get("color") in ("s", "q", "cls") else {})}))
        present_s = list(dict.fromkeys(t["s"]))
        if any(t["irs"]):
            presets.append(Preset("with_irs", "With a Spitzer IRS spectrum", "filter", {"filters": {"flags": {"irs": 1}}}))
        if any(t["sat"]):
            presets.append(Preset("unsaturated", "No saturation-risk flag", "filter", {"filters": {"flags": {"sat": 0}}}))
        if "good" in set(t["q"]):
            presets.append(Preset("good_quality", "Quality tier good", "filter", {"filters": {"cats": {"q": ["good"]}}}))
        if "globulars" in present_s and len(present_s) > 1:
            presets.append(Preset("point_sources", "Point sources (no globular-cluster pointings)", "filter",
                                  {"filters": {"cats": {"s": [s for s in present_s if s != "globulars"]}}}))
        default = "default" if any(p.key == "default" for p in presets) else next(
            (p.key for p in presets if p.kind == "axes"), "pca")
        n_irs = int(np.count_nonzero(t["irs"]))
        return CatalogSpec(
            key="src", table=t, id="id", ra="ra", dec="dec", columns=cols, virtual=virt, groups=groups,
            presets=presets, manifold=ManifoldSpec(dims=mdims, frames={}, default_frame=default),
            title=f"SPHEREx sources ({len(t):,})", noun=("source", "sources"),
            caveats=["Magnitudes are synthetic JWST/NIRCam Vega magnitudes integrated over each SPHEREx spectrum; "
                     "a filter is kept only where the spectrum samples most of its throughput.",
                     "SPHEREx stops near 4.97 µm, so F444W and F480M are truncated for nearly every source and read "
                     "slightly faint (the tb_ flags and tbcount mark them).",
                     "Quality tiers are flags, not a cut: poor and marginal sources stay in every view.",
                     f"{n_irs:,} sources also carry a Spitzer IRS spectrum, drawn as a second segment and not rescaled.",
                     "The samples were selected independently; the loci are not a controlled comparison."])

