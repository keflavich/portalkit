"""--replace backups (stub and inplace) and rollback, on fake legacy directories."""

from __future__ import annotations

import importlib
import json
import os
from pathlib import Path

import pytest

from portalkit import schema
from portalkit.deploy import (DeployError, OwnershipConflict, SymlinkRefusal, UsageError,
                              VerifyFailure)
from portalkit.deploy.exposure import scan

dmod = importlib.import_module("portalkit.deploy.deploy")
bmod = importlib.import_module("portalkit.deploy.backup")

FAM = "fam"
BID = "20261010T120000Z-0123abcd"
BID2 = "20261011T120000Z-89abcdef"
LEGACY = "<html><body>legacy map, generated by make_map.py</body></html>\n"


def stage_portal(root: Path, bid: str = BID, title: str = "v1") -> Path:
    d = root / FAM / bid / "main"
    page = {"assets": "./assets/", "datasets": {"src": {"url": "data/src/manifest.json"}},
            "links": {"home": "index.html"}}
    content = {
        "portal.json": json.dumps({"pages": [{"id": "map", "file": "map.html"},
                                             {"id": "cat", "file": "cat.html"}]}),
        "map.html": ('<!doctype html><title>' + title + '</title><script id="pk-page" '
                     'type="application/json">' + json.dumps(page) + '</script>'
                     '<link rel="stylesheet" href="assets/pk.css">\n'),
        "data/src/manifest.json": "{}",
        "assets/pk.css": "body{}",
    }
    for rel, text in content.items():
        p = d / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return d


@pytest.fixture()
def world(tmp_path: Path) -> dict:
    legacy = tmp_path / "orange" / "proj" / "portal"
    (legacy / "sub dir").mkdir(parents=True)
    sec = tmp_path / "web" / "secure"
    sec.mkdir(parents=True)
    (tmp_path / "web" / "public").mkdir()
    os.symlink(tmp_path / "orange" / "proj", sec / "proj")
    emap = scan({"public": tmp_path / "web" / "public", "secure": sec}, cache_s=0)
    old = legacy / "old_map.html"
    old.write_text(LEGACY)
    os.utime(old, (1.6e9, 1.6e9))
    stage = tmp_path / "stage"
    stage_portal(stage)
    return {"legacy": legacy, "target": legacy / "unified", "emap": emap, "stage": stage}


def site(world: dict, legacy=("old_map.html",), preset: str = "ccd") -> dict:
    return {"family": FAM, "portal": [{
        "id": "main", "visibility": "secure", "legacy_dir": str(world["legacy"]),
        "page": [{"id": "map", "legacy": list(legacy), "preset": preset},
                 {"id": "cat", "legacy": ["old_cat.html"]}]}]}


def run(world: dict, s: dict | None = None, bid: str = BID, **kw):
    kw.setdefault("replace", "stub")
    return dmod.deploy(FAM, bid, s or site(world), stage_root=world["stage"],
                       emap=world["emap"], **kw)


def manifest(world: dict) -> dict:
    return json.loads((world["target"] / dmod.MANIFEST_NAME).read_text())


