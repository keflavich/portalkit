HST_BANDPASS: dict[str, str] = {}
PCT = (0.5, 99.5)


def _fid(key: str) -> str | None:
    m = re.fullmatch(r"(?:m_)?(f\d{3}[wmn])", key)
    if m:
        return f"JWST/NIRCam.{m.group(1).upper()}"
    h = re.fullmatch(r"m_hst_(\w+)", key)
    return HST_BANDPASS.get(h.group(1)) if h else None


def _slug(name: str, taken: set) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "layer"
    k, i = s, 2
    while k in taken:
        k, i = f"{s}_{i}", i + 1
    taken.add(k)
    return k


def _const(text: str, name: str):
    m = re.search(rf"\b{name}\s*=\s*", text)
    if m is None:
        raise ValueError(f"no {name} in the legacy page")
    return json.JSONDecoder().raw_decode(text, m.end())[0]


def _surveys(text: str) -> list[list[str]]:
    """The manifold page's cutout SURVEYS (``['name', `${AVM}/dir/`]`` template literals)."""
    return [[n, AVM + d] for n, d in re.findall(r"\['([^']+)', `\$\{AVM\}/([^`]+)`\]", text)]


def _pct(x: np.ndarray) -> tuple[float, float]:
    x = x[np.isfinite(x)]
    if x.size < 2:
        return (0.0, 1.0)
    lo, hi = np.percentile(x, PCT)
    return (round(float(lo), 3), round(float(hi), 3)) if hi > lo else (float(lo) - 0.5, float(lo) + 0.5)


def _span(rungs) -> str:
    um = [float(x) for r in rungs for x in re.findall(r"([\d.]+)\s*μm", r["label"])]
    return f"{min(um):g}-{max(um):g} um" if um else "multi-band"


def _sel(ids, ds: str) -> str:
    """Saved selection (section 6.3): ``ids:`` up to IDS_IN_HASH_MAX ids, else a deflated recipe."""
    from portalkit.constants import IDS_IN_HASH_MAX
    from portalkit.legacy.hashmap import encode_recipe
    ids = [str(i) for i in ids]
    if len(ids) <= IDS_IN_HASH_MAX:
        return "ids:" + ",".join(ids)
    return encode_recipe([{"op": "replace", "kind": "ids", "view": {"ds": ds}, "ids": ids}])


def _rows(R, D, ra, dec) -> np.ndarray:
    """Catalogue row of every map_ccd entry: the kept rows are in catalogue order and carry
    ``round(ra, 5)``/``round(dec, 5)``, so one forward walk finds each."""
    r5 = [round(float(x), 5) for x in ra]
    d5 = [round(float(x), 5) for x in dec]
    out, i, n = np.empty(len(R), dtype=np.int64), 0, len(r5)
    for j, (a, b) in enumerate(zip(R, D)):
        while i < n and not (r5[i] == a and d5[i] == b):
            i += 1
        if i == n:
            raise ValueError(f"map_ccd entry {j} ({a}, {b}) has no catalogue row after the previous one")
        out[j], i = i, i + 1
    return out


class Wd2Adapter:
    name = "wd2"
    tiers = ("A", "B")

    # -- raw data per tier ----------------------------------------------------------------
    def _read(self, ctx, name: str) -> str:
        p = LEGACY_DIR / name
        ctx.inputs.add(p)
        return p.read_text(encoding="utf-8")

    def _tier_a(self, ctx) -> dict:
        from portalkit.legacy import extract
        mani = extract.payload(self._read(ctx, "wd2_manifold.html"), names=("DATA",))
        ccd_html = self._read(ctx, "map_ccd.html")
        ccd = extract.payloads(ccd_html, names=())[0]["value"][0]
        way = json.loads(self._read(ctx, "waypoints_wd2_wavelength.json"))["waypoints"][0]
        rungs = [(w["wavelength"], w["url"], w["label"], w["description"])
                 for w in way["wavelength_slider"]["wavelengths"]]
        iso = mani["isochrone"]
        return {"mani": mani, "sabbi": extract.payload(self._read(ctx, "sabbi.html"), names=("DATA",)),
                "ccd": ccd, "bases": _const(ccd_html, "BASES"), "overlays": _const(ccd_html, "OVERLAYS"),
                "center": _const(ccd_html, "CENTER"), "fov": float(way["fov"]), "rungs": rungs,
                "surveys": _surveys(self._read(ctx, "wd2_manifold.html")),
                "iso": (math.log10(float(iso["age_myr"]) * 1e6), float(iso["distance_pc"]))}

    def _tier_b(self, ctx) -> dict:
        M, S, C, W = (ctx.legacy.module(m) for m in MODULES)
        if {os.path.realpath(C.DEFAULT_CATALOG), os.path.realpath(M.DEFAULT_CATALOG)} != {os.path.realpath(CATALOG)}:
            raise ValueError(f"WD2 catalogues differ: {M.DEFAULT_CATALOG}, {C.DEFAULT_CATALOG}, {CATALOG}")

        def deps(mod, *names):
            paths = [mod.__file__] + [getattr(mod, n, None) for n in names]
            return [p for p in paths if isinstance(p, str) and os.path.exists(p)]

        def mani():           # WD2_Portal_Manifold.main() up to the HTML template
            names, dims, stars, ew9 = M.build(M.DEFAULT_CATALOG, min_filt=M.MIN_FILT_INDEPENDENT,
                                              miri_catalog=M.DEFAULT_MIRI_CATALOG,
                                              ewocs9_table=M.DEFAULT_EWOCS9_TABLE)
            sdims = M.standardize(names, dims)
            keys, presets = {d["key"] for d in sdims}, []
            for p in M.PRESETS:
                p = dict(p)
                if p["id"] == "pca":
                    p["x"], p["y"], npca, frac = M.pca_frame(sdims, M.PCA_KEYS)
                    p["note"] += f" {npca} stars; PC1 carries {frac[0]:.0%} of the variance, PC2 {frac[1]:.0%}."
                if set(p["x"]) | set(p["y"]) <= keys:
                    presets.append(p)
            cats = [dict(c, colors={"0-5": "#8a93a6", **c["colors"]})
                    if c["key"] == "obs" and any(s["obs"] == "0-5" for s in stars) else c for c in M.CATEGORIES]
            clusters = {k: {"label": lab, "names": nm} for k, (lab, nm) in M.load_cluster_selections().items()}
            return {"stars": stars, "dims": sdims, "groups": [list(g) for g in M.GROUPS], "presets": presets,
                    "categories": cats, "ewocs9": ew9, "clusters": clusters}

        def sabbi():
            names, dims, stars = S.build()
            sdims = S.standardize(names, dims)
            keys = {d["key"] for d in sdims}
            return {"stars": stars, "dims": sdims, "groups": [list(g) for g in S.GROUPS],
                    "categories": S.CATEGORIES,
                    "presets": [p for p in S.PRESETS if set(p["x"]) | set(p["y"]) <= keys]}
        clusters = [p for _, p in M.CLUSTER_SELECTIONS.values() if os.path.exists(p)]
        m_in = deps(M, "DEFAULT_CATALOG", "DEFAULT_MIRI_CATALOG", "DEFAULT_EWOCS9_TABLE", "SABBI_FULL_REG",
                    "M8_CATALOG", "EWOCS_CATALOG", "NIRSPEC_SOURCES_ECSV") + clusters
        tpl = Path(M.__file__).with_name("WD2_Portal_Manifold_template.html")
        ctx.inputs.add(tpl)
        return {"mani": ctx.cache.memo("wd2_manifold_v1", mani, inputs=m_in),
                "sabbi": ctx.cache.memo("wd2_sabbi_v1", sabbi,
                                        inputs=deps(S, "SABBI_H5", "SABBI_FULL_REG", "EWOCS_CATALOG")),
                "ccd": ctx.cache.memo("wd2_mapccd_v1", lambda: C.jwst_dataset(C.DEFAULT_CATALOG),
                                      inputs=deps(C, "DEFAULT_CATALOG", "SABBI_REG", "SABBI_FULL_REG",
                                                  "SABBI_H5", "EWOCS_CATALOG")),
                "bases": [list(b) for b in C.BASES], "overlays": [list(o) for o in C.OVERLAYS],
                "center": list(C.CENTER), "fov": float(W.WD2_FOV), "rungs": [tuple(w) for w in W.WAVELENGTHS],
                "surveys": _surveys(tpl.read_text(encoding="utf-8")),
                "iso": (float(M.ISOCHRONE_AGE_LOG10_YR), float(M.WD2_DISTANCE_PC))}

    # -- datasets -------------------------------------------------------------------------
    def datasets(self, ctx):
        from astropy.table import Table
        from portalkit.legacy import extract
        from portalkit.spec import (ExtinctionSpec, FilterSetSpec, ForeignRecords, ReadmeSpec,
                                    RecordSetSpec, TemplateSpec, TierUnavailable)
        if ctx.tier not in self.tiers:
            raise TierUnavailable(f"wd2 implements tiers A and B, not {ctx.tier}")
        raw = self._tier_a(ctx) if ctx.tier == "A" else self._tier_b(ctx)
        ctx.inputs.add(SED_ECSV)
        raw["sed"] = Table.read(SED_ECSV)
        raw["diagrams"] = extract.payload(self._read(ctx, "wd2_colorcolor.html"), names=("DIAGRAMS",))
        ctx.inputs.add(CATALOG)
        cat = Table.read(CATALOG, format="ascii.ecsv", include_names=["RA", "DEC"])
        raw["ccd_rows"] = _rows(raw["ccd"]["R"], raw["ccd"]["D"], np.asarray(cat["RA"], float),
                                np.asarray(cat["DEC"], float))
        self._raw = raw
        lim = ctx.limit
        names = [s["n"] for s in raw["mani"]["stars"]]
        pos = {n: i for i, n in enumerate(names)}
        sed_names = [str(n) for n in raw["sed"]["name"]]
        sed_keep = np.arange(len(sed_names)) if lim is None else np.arange(min(lim, len(sed_names)))
        keep = np.arange(len(names)) if lim is None else np.unique(np.concatenate([
            np.arange(min(lim, len(names))), [i for i, s in enumerate(raw["mani"]["stars"]) if s.get("spec")],
            [pos[sed_names[i]] for i in sed_keep if sed_names[i] in pos]])).astype(int)
        nc, ns = len(raw["ccd"]["R"]), len(raw["sabbi"]["stars"])
        ds = {"src": self._src(raw, keep, set(sed_names)), "ccd": None,     # ccd needs the src/seds ids
              "sabbi": self._mani(raw["sabbi"], "sabbi", np.arange(ns if lim is None else min(lim, ns)),
                                  title="Sabbi+2020 HST catalogue x EWOCS NIRCam",
                                  caveats=["Sabbi+2020 HST magnitudes carry no filter curve: the "
                                           "catalogue names its bands Im/V/J/H without the ACS/WFC3 "
                                           "bandpass, so the live SED uses the EWOCS NIRCam magnitudes only.",
                                           "Light curves are not part of this portal: the periodicity "
                                           "class and variability statistics are shown, the time series "
                                           "are not."])[0]}
        ds["seds"] = self._seds(raw, sed_keep, pos)
        ds["ccd"] = self._ccd(raw, np.arange(nc if lim is None else min(lim, nc)),
                              {str(i) for i in ds["src"].table["id"]}, {str(i) for i in ds["seds"].table["id"]})
        ds["sedimg"], ds["sedfig"] = self._img(ds["seds"], "seds"), self._img(ds["seds"], "src", ds["src"])
        ds["hips"], ds["iso"] = self._hips(raw), self._iso(ctx, raw)
        # the NIRSpec 2640 spectra, read from that portal's shards (no copy is written here)
        # (ids: the foreign record ids the src rows name, for the record count only)
        ds["nirspec"] = RecordSetSpec("nirspec", "pks1", "src", sorted({str(s) for s in ds["src"].table["spec"] if s}),
                                      None, noun=("spectrum", "spectra"),
                                      foreign=ForeignRecords(SPEC_BASE, SPEC_KEY, id_column="spec"))
        ds.update(tpl=TemplateSpec(), ext=ExtinctionSpec(),
                  flt=FilterSetSpec(keys=sorted({_fid(c.key) for c in ds["src"].columns if _fid(c.key)})))
        ds["readme"] = ReadmeSpec(markdown=self._readme(ctx, raw, ds))
        return ds

    def _mani(self, pl, key, keep, *, title, caveats, extra=(), cols_extra=None):
        """A legacy manifold payload (stars + standardized dims) -> CatalogSpec with manifold."""
        from astropy.table import Table
        from portalkit.bundle.codec import col_stats
        from portalkit.constants import T0_MAX
        from portalkit.legacy.manifold_payload import preset_frame
        from portalkit.spec import CatalogSpec, ColumnSpec, DensitySpec, Group, ManifoldSpec, Preset, VirtualDim
        stars = [pl["stars"][i] for i in keep]
        vals = {d["key"]: np.array(d["v"], dtype=float)[keep] for d in pl["dims"]}
        t = Table({"id": [s["n"] for s in stars], "ra": [float(s["ra"]) for s in stars],
                   "dec": [float(s["dec"]) for s in stars]})
        cols, virt, kmap, factor, rng = [ColumnSpec("id", "id")], [], {}, {}, {}
        for c in pl["categories"]:
            present = list(dict.fromkeys(str(s[c["key"]]) for s in stars))
            t[c["key"]] = [str(s[c["key"]]) for s in stars]
            lv = [x for x in c["colors"] if x in present] + [x for x in present if x not in c["colors"]]
            cols.append(ColumnSpec(c["key"], "category", label=c["label"], levels=lv,
                                   colors={k: v for k, v in c["colors"].items() if k in lv}))
        for d in pl["dims"]:
            k, v = d["key"], vals[d["key"]]
            if k.startswith("c_"):
                toks = k[2:].split("_")
                hst = toks[0] == "hst"
                toks = toks[1:] if hst else toks
                ab = [next((c for c in ([f"m_hst_{x}"] if hst else []) + [f"m_{x}", f"m_miri_{x}", f"m_hst_{x}"]
                            if c in vals), None) for x in toks] if len(toks) == 2 else [None]
                if None not in ab:
                    diff = vals[ab[0]] - vals[ab[1]]
                    fin = np.isfinite(v)
                    if np.array_equal(fin, np.isfinite(diff)) and np.all(np.abs(v[fin] - diff[fin]) < 5e-5):
                        kmap[k] = f"{ab[0]}-{ab[1]}"
                        virt.append(VirtualDim(kmap[k], label=d["label"], unit=d["unit"], group=d["group"]))
                        rng[kmap[k]] = tuple(d["range"])
                        continue
            kmap[k], rng[k] = k, tuple(d["range"])
            log, lab, note = bool(d.get("log")), d["label"], d.get("note") or ""
            if k.startswith("m_"):
                t[k] = v = np.round(v, 3)
                cols.append(ColumnSpec(k, "mag", label=lab, unit=d["unit"], filter=_fid(k), step=0.001,
                                       group=d["group"], note=note, invert=d["scale"] < 0))
            else:
                t[k] = v
                cols.append(ColumnSpec(k, "value", label=f"log10 {lab}" if log and "log" not in lab.lower() else lab,
                                       unit=d["unit"], group=d["group"], invert=True if d["scale"] < 0 else None,
                                       note=(note + " (stored as log10 values)").strip() if log else note))
            fin = v[np.isfinite(v)]
            if fin.size and d["scale"]:
                factor[k] = col_stats(fin)["scale"] / d["scale"]
        for c in cols_extra or ():
            t[c[0].key] = c[1]
            cols.append(c[0])
        dims = [kmap[d["key"]] for d in pl["dims"]]
        groups = [Group(g, lab, [kmap[d["key"]] for d in pl["dims"] if d["group"] == g])
                  for g, lab in pl["groups"]]
        presets, dens, frames = [], [], {}
        colkeys = {c.key for c in cols}
        for p in pl["presets"]:
            x, y = ({kmap.get(a, a): w for a, w in p[ax].items()} for ax in ("x", "y"))
            if not set(x) | set(y) <= set(dims):
                continue
            data = {"note": p.get("note", ""), "code": p.get("code", ""),
                    **({"color": p["color"]} if p.get("color") in colkeys else {})}
            if len(x) == 1 and len(y) == 1 and set(x.values()) | set(y.values()) == {1}:
                (xk,), (yk,) = x, y
                presets.append(Preset(p["id"], p["name"], "axes", {**data, "x": xk, "y": yk}))
                if len(t) > T0_MAX:
                    dens.append(DensitySpec(p["id"], xk, yk, xr=rng[xk], yr=rng[yk]))
            else:
                frames[p["id"]] = preset_frame(x, y, dims, factor)
                presets.append(Preset(p["id"], p["name"], "frame", {**data, "dims": dims, "F": frames[p["id"]]}))
        for pk, lab, xk, yk, note in extra:
            presets.append(Preset(pk, lab, "axes", {"x": xk, "y": yk, "note": note}))
            if len(t) > T0_MAX:
                dens.append(DensitySpec(pk, xk, yk, xr=_pct(self._expr(t, xk)), yr=_pct(self._expr(t, yk))))
        # an axes preset may be the default frame (the manifold pane resolves preset keys)
        default = "pca" if "pca" in frames else next(p.key for p in presets if p.kind in ("axes", "frame"))
        # legacy colour key -> virtual dim (c_f115w_f150w -> m_f115w-m_f150w), for the legacy
        # share links (page.legacy.dim_alias; kv-view x/y/c name the legacy keys)
        if not hasattr(self, "_alias"):
            self._alias = {}
        self._alias[key] = {k: v for k, v in kmap.items() if k != v}
        spec = CatalogSpec(key=key, table=t, id="id", columns=cols, ra="ra", dec="dec", virtual=virt,
                           groups=[g for g in groups if g.dims], presets=presets, density=dens,
                           manifold=ManifoldSpec(dims=dims, frames=frames, default_frame=default),
                           title=f"{title} ({len(t):,} stars)", caveats=list(caveats))
        return spec, kmap, vals

    @staticmethod
    def _expr(t, e: str) -> np.ndarray:
        a, _, b = e.partition("-")
        x = np.asarray(t[a], dtype=float)
        return x - np.asarray(t[b], dtype=float) if b else x

    def _src(self, raw, keep, sed_names: set):
        from portalkit.spec import ColumnSpec, Preset
        pl = raw["mani"]
        stars = [pl["stars"][i] for i in keep]
        spec = [str(s.get("spec") or "") for s in stars]
        extra_cols = [(ColumnSpec("sed", "flag", label="SED figure"),
                       np.array([s["n"] in sed_names for s in stars])),
                      (ColumnSpec("spec", "text", label="NIRSpec 2640 source"), spec),
                      (ColumnSpec("spec_url", "url", label="NIRSpec spectrum",
                                  note="opens the source in the NIRSpec 2640 portal"),
                       [SPEC_LINK.format(s) if s else "" for s in spec])]
        if any("ew9" in s for s in stars):
            extra_cols.append((ColumnSpec("ew9", "category", label="EWOCS-IX type"),
                               [str(s.get("ew9", "")) for s in stars]))
        mk = {d["key"] for d in pl["dims"] if d["key"].startswith("m_")}

        def ex(fs):       # None when a filter is not a manifold dim (the diagram is skipped)
            parts = [next((c for c in (f"m_{f}", f"m_miri_{f}", f"m_hst_{f}") if c in mk), None) for f in fs]
            return None if None in parts else "-".join(parts)
        diag = [d for d in raw["diagrams"] if ex(d["xfilters"]) and ex(d["yfilters"])]
        extra = [(f"cc_{d['key']}", d["title"].split("  (")[0], ex(d["xfilters"]), ex(d["yfilters"]),
                  d.get("note", "")) for d in diag]
        cat, kmap, vals = self._mani(pl, "src", keep, title="Wd2 NIRCam stars", extra=extra, cols_extra=extra_cols,
                                     caveats=["Magnitudes need S/N >= 10; stars are detected independently "
                                              "in at least 6 filters (legacy n_filt_independent cut).",
                                              "MIRI magnitudes are DAOPHOT instrumental VEGAMAG on their own "
                                              "zero point; HST magnitudes come from Sabbi+2020 through the "
                                              "EWOCS crossmatch, which does not name their ACS/WFC3 bandpass. "
                                              "Neither carries a filter curve, so the live SED uses the "
                                              "NIRCam magnitudes only.",
                                              "NIRSpec spectra are read from the NIRSpec 2640 portal's record "
                                              "shards (matched on the 'spec' column); each star also links there."])
        ids = np.array([s["n"] for s in stars])

        def fin(k):
            return np.isfinite(vals[k]) if k in vals else np.zeros(len(stars), bool)
        sets = [("hasSpec", "Has NIRSpec spectrum", np.array([bool(s) for s in spec])),
                ("fullCov", "Full photometric coverage", np.array([s["obs"] == "15-16" for s in stars])),
                ("iceOutlier", "Ice colour outlier (F250M-F300M < 0, F323N-F335M > 0.4)",
                 fin("c_f250m_f300m") & fin("c_f323n_f335m")
                 & (np.nan_to_num(vals.get("c_f250m_f300m", np.zeros(len(stars))), nan=1) < 0.0)
                 & (np.nan_to_num(vals.get("c_f323n_f335m", np.zeros(len(stars))), nan=0) > 0.4)),
                ("sabbi", "Sabbi+2020 HST match", np.any([fin(f"m_hst_{b}") for b in HST], axis=0)),
                ("ew9All", "EWOCS-IX substellar candidates", np.array(["ew9" in s for s in stars])),
                ("ew9Strong", "EWOCS-IX strong", np.array([s.get("ew9") == "S" for s in stars])),
                ("ew9Disk", "EWOCS-IX with disk", np.array([bool(s.get("ew9d")) for s in stars]))]
        have = set(ids)
        for k, c in (pl.get("clusters") or {}).items():
            sets.append((k, c["label"], np.isin(ids, [n for n in c["names"] if n in have])))
        cat.presets += [Preset(k, lab, "selection", {"sel": _sel(ids[m], "src")}) for k, lab, m in sets if m.any()]
        full = next((p for p in cat.presets if p.key == "fullCov"), None)
