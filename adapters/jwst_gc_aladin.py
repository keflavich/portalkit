"""jwst_gc_aladin: JWST Galactic Center HiPS + catalog sky explorer (WP32 extra;
ARCHITECTURE.md section 14 / docs/port_table.json "jwst_gc_aladin.html (critic)").

Legacy: ``/orange/adamginsburg/web/public/avm_images/jwst_gc_aladin.html`` -- a hand-maintained
Aladin Lite v3 page (no HTML generator; per ``docs/inventory.json``) with:

* a base-survey ``<select>`` (CDS HiPS ids, MeerKAT 1284 MHz Stokes I selected by default);
* three JS arrays of HiPS overlay layers (``LAYERS`` -- JWST composites, ``ALMA_LAYERS``,
  ``STAR_LAYERS`` -- FITS-tile density/colour maps of the nearest stars), each a flat,
  single-quoted JS object literal (not JSON);
* a ``STAR_CATALOG`` catalog-HiPS of 3.3M stars (``jwst-stars-catalog-hips``, generated by
  ``jwst_gc_pipeline/cmz/hipsgen.py`` via Hipsgen-cat -- too large to re-encode as a portalkit
  catalog, so it is not carried over; see ``contract_issues``/``deviations``);
* a ``CATALOGS`` object of small point-source overlays (ultrared stars, SgrB2/CMZoom/ACES
  compact sources, guide stars, proper-motion catalogs...), each fetched from its own sidecar
  ``jwst_gc_cat_*.json``/``jwst_ultrared_stars.json`` file next to the page. ``CATALOGS`` itself
  embeds JS filter functions and is not valid JSON either, so this adapter discovers the
  sidecar *data* files directly (the thing ``CATALOGS`` ultimately points at) rather than
  parsing that object;
* five view buttons (``data-go="ra dec fov"``), the first ("All data") giving the default
  sky target, the rest -> ``HipsSpec.bookmarks``.

This adapter parses the three flat JS-object-literal arrays with a small brace-aware regex
(``_parse_js_objects``; they have no nested braces, so a ``\\{([^{}]*)\\}`` scan plus a
``key: 'str'|true|false|number`` pair grammar is enough -- no JS engine needed) and discovers
the sidecar catalog files by glob, merging the ones it can read into a single
:class:`~portalkit.spec.CatalogSpec` of ``id``/``ra``/``dec``/``source`` rows (no numeric or
category columns, by design -- see the module docstring's flag-matching note below).

Tier A only (``tiers = ("A",)``).
"""

from __future__ import annotations

import re
from pathlib import Path

from portalkit.spec import CatalogSpec, HipsSpec, ReadmeSpec, TierUnavailable, catalog_from_rows

AVM_DIR = Path("/orange/adamginsburg/web/public/avm_images")
HTML_FILE = AVM_DIR / "jwst_gc_aladin.html"
#: same public AVM tile tree adapters/hips_tours.py's HiPS rungs live under (the legacy page's
#: own JS builds this from its own URL -- `ROOT = new URL('.', location.href).href` -- which
#: resolves to the same tree under whichever mirror domain serves the page).
AVM = "https://data.rc.ufl.edu/pub/adamginsburg/avm_images/"

#: sidecar catalog JSON files the legacy CATALOGS object fetches, by key -> filename. The key
#: becomes the merged catalog's "source" value. ``jwst_gc_cat_kmos_pointings.json`` is listed
#: in the legacy HTML's CATALOGS object/<select> but is absent on disk (confirmed 2026-10-12);
#: it is silently skipped here (not raised) and reported in contract_issues instead.
SIDECARS: dict[str, str] = {
    "ultrared": "jwst_ultrared_stars.json",
    "sgrb2_alma": "jwst_gc_cat_sgrb2_alma.json",
    "cmzoom": "jwst_gc_cat_cmzoom.json",
    "aces_compact": "jwst_gc_cat_aces_compact.json",
    "kmos": "jwst_gc_cat_kmos_pointings.json",
    "guidestars": "jwst_gc_cat_guidestars.json",
    "sgrb2_pm": "jwst_gc_cat_sgrb2_treasury_pm.json",
    "arches_pm": "jwst_gc_cat_arches_treasury_pm.json",
    "brick_pm": "jwst_gc_cat_brick_treasury_pm.json",
    "cloudc_pm": "jwst_gc_cat_cloudc_treasury_pm.json",
    "cloudef_pm": "jwst_gc_cat_cloudef_treasury_pm.json",
    "quintuplet_pm": "jwst_gc_cat_quintuplet_treasury_pm.json",
}

_OBJ_RE = re.compile(r"\{([^{}]*)\}")
_PAIR_RE = re.compile(r"(\w+)\s*:\s*(?:'((?:[^'\\]|\\.)*)'|(true|false)|([-+0-9.eE]+))")
_SELECT_RE = re.compile(r'<select id="base"[^>]*>(.*?)</select>', re.S)
_OPTION_RE = re.compile(r"<option\s+([^>]*)>([^<]*)</option>")
_GO_RE = re.compile(r'data-go="([-0-9. ]+)"[^>]*>([^<]*)<')
_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slug(text: str) -> str:
    return _SLUG_RE.sub("_", text.lower()).strip("_") or "x"


def _parse_js_objects(text: str) -> list[dict]:
    """Flat (non-nested) ``{key: 'str'|true|false|number, ...}`` JS object literals of
    ``text`` -> a list of plain dicts, in order. Keys with no recognised value are omitted;
    an object with no recognised keys is skipped."""
    out = []
    for om in _OBJ_RE.finditer(text):
        d: dict = {}
        for pm in _PAIR_RE.finditer(om.group(1)):
            key, s, b, n = pm.groups()
            if s is not None:
                d[key] = s
            elif b is not None:
                d[key] = (b == "true")
            elif n is not None:
                d[key] = float(n) if ("." in n or "e" in n.lower()) else int(n)
        if d:
            out.append(d)
    return out


def _js_array(text: str, name: str) -> list[dict]:
    """``_parse_js_objects`` of the ``const|let|var NAME = [ ... ];`` array literal of
    ``text``, or ``[]`` if ``NAME`` is not found."""
    m = re.search(r"\b(?:const|let|var)\s+" + re.escape(name) + r"\s*=", text)
    if not m:
        return []
    i = text.find("[", m.end())
    j = text.find("];", i)
    if i < 0 or j < 0:
        return []
    return _parse_js_objects(text[i + 1:j])


def base_surveys(text: str) -> list[dict]:
    """``[{id, name, url, default}]`` from the ``<select id="base">`` options of ``text``."""
    m = _SELECT_RE.search(text)
    if not m:
        return []
    out = []
    taken: set = set()
    for om in _OPTION_RE.finditer(m.group(1)):
        attrs, label = om.group(1), om.group(2).strip()
        vm = re.search(r'value="([^"]*)"', attrs)
        if not vm:
            continue
        sid = _slug(label)
        while sid in taken:
            sid += "_"
        taken.add(sid)
        out.append({"id": sid, "name": label, "url": vm.group(1),
                    "default": "selected" in attrs})
    return out


def view_buttons(text: str) -> list[dict]:
    """``[{ra, dec, fov, name}]`` from every ``data-go="ra dec fov"`` button of ``text``, in
    document order (the first is the page's default view)."""
    out = []
    for m in _GO_RE.finditer(text):
        parts = m.group(1).split()
        if len(parts) != 3:
            continue
        try:
            ra, dec, fov = (float(p) for p in parts)
        except ValueError:
            continue
        out.append({"ra": ra, "dec": dec, "fov": fov, "name": m.group(2).strip()})
    return out


def hips_overlays(text: str) -> list[dict]:
    """Overlay dicts (``{id, name, url, opacity, default}``) from the legacy ``LAYERS``,
    ``ALMA_LAYERS`` and ``STAR_LAYERS`` JS arrays, in that order."""
    out = []
    taken: set = set()
    for name in ("LAYERS", "ALMA_LAYERS", "STAR_LAYERS"):
        for layer in _js_array(text, name):
            lid = str(layer.get("id") or _slug(str(layer.get("name", name))))
            while lid in taken:
                lid += "_"
            taken.add(lid)
            d = str(layer.get("dir", "")).strip("/")
            if not d:
                continue
            out.append({"id": lid, "name": str(layer.get("name", lid)), "url": f"{AVM}{d}/",
                       "opacity": float(layer.get("opacity", 1.0)),
                       "default": bool(layer.get("on", False))})
    return out


def discover_catalogs(ctx) -> dict[str, list[dict]]:
    """``{source: sources}`` for every :data:`SIDECARS` file present on disk; a listed file
    that is missing or unreadable is skipped (never raised) -- the caller folds the absence
    into its own build report instead."""
    out: dict[str, list[dict]] = {}
    for source, fname in SIDECARS.items():
        p = AVM_DIR / fname
        if not p.is_file():
            continue
        ctx.inputs.add(p)
        import json
        try:
            doc = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        srcs = doc.get("sources") if isinstance(doc, dict) else None
        if not isinstance(srcs, list):
            continue
        rows = [s for s in srcs if isinstance(s, dict) and "ra" in s and "dec" in s]
        if rows:
            out[source] = rows
    return out


def merged_catalog_rows(by_source: dict[str, list[dict]]) -> list[dict]:
    """One ``{id, ra, dec, source}`` row per star of every catalog of ``by_source``, ``id``
    made unique with a per-source running index."""
    rows: list[dict] = []
    for source, srcs in by_source.items():
        for i, s in enumerate(srcs):
            try:
                ra, dec = float(s["ra"]), float(s["dec"])
            except (TypeError, ValueError):
                continue
            rows.append({"id": f"{source}_{i}", "ra": ra, "dec": dec, "source": source})
    return rows


README = """# JWST Galactic Center sky explorer

JWST NIRCam/MIRI Treasury mosaics of the Galactic Center (CMZ), shown as stacked HiPS layers
over a selectable base survey (MeerKAT 1284 MHz Stokes I by default), with point-source
catalogs (ultrared stars, SgrB2/CMZoom/ACES compact sources, guide stars, proper-motion
catalogs) overlaid as sky markers.

## Caveats

- The 3.3M-star `jwst-stars-catalog-hips` catalog-HiPS the legacy page overlays (generated by
  `jwst_gc_pipeline/cmz/hipsgen.py`) is not re-encoded here; only the small, already-JSON
  point-source sidecar catalogs are.
- The legacy page's ALMA data-cube line/product selector and JWST focal-plane footprint
  overlay are not ported.
"""


class JwstGcAladinAdapter:
    name = "jwst_gc_aladin"
    tiers = ("A",)

    def datasets(self, ctx):
        if ctx.tier not in self.tiers:
            raise TierUnavailable(f"jwst_gc_aladin implements tier A only, not {ctx.tier}")
        if not HTML_FILE.is_file():
            raise FileNotFoundError(f"jwst_gc_aladin: legacy page not found: {HTML_FILE}")
        ctx.inputs.add(HTML_FILE)
        text = HTML_FILE.read_text(encoding="utf-8")
        base = base_surveys(text)
        if not base:
            raise ValueError(f"{HTML_FILE}: no base-survey <select> options found")
        overlays = hips_overlays(text)
        views = view_buttons(text)
        target = {"ra": views[0]["ra"], "dec": views[0]["dec"], "fov": views[0]["fov"]} \
            if views else None
        bookmarks = [{"name": v["name"], "ra": v["ra"], "dec": v["dec"], "fov": v["fov"]}
                     for v in views[1:]]
        hips = HipsSpec(base=base, overlays=overlays, target=target,
                        bookmarks=bookmarks or None)
        by_source = discover_catalogs(ctx)
        rows = merged_catalog_rows(by_source)
        if ctx.limit is not None:
            rows = rows[: ctx.limit]
        cat: CatalogSpec | None = None
        if rows:
            cat = catalog_from_rows(
                rows, "id", "ra", "dec", roles={"source": "text"}, key="stars",
                title="JWST GC point-source catalogs",
                columns={"source": {"label": "catalog"}})
            cat.caveats = [f"{len(by_source)} of {len(SIDECARS)} legacy sidecar catalogs "
                          "found and merged (see contract_issues for the rest)."]
        ds: dict = {"sky": hips, "readme": ReadmeSpec(markdown=README)}
        if cat is not None:
            ds["stars"] = cat
        self._has_cat = cat is not None
        return ds

    def pages(self, ctx, ds):
        from portalkit.spec import PageSpec as P
        datasets = [k for k in ("sky", "stars", "readme") if k in ds]
        layout = None
        caps_disable: dict[str, str] = {}
        if self._has_cat:
            # An explicit single-pane layout (rather than the explorer archetype's default
            # list+sky+detail core) -- the legacy page is a pure sky view with layer-toggle
            # side panels, never a per-source list or detail panel, and giving the resolver a
            # second/third pane bound to the same catalog would also incorrectly flag "multi"
            # (section 8.1) for what is a single-dataset page.
            layout = {"pane": "sky", "dataset": "stars", "options": {"hips": "sky"}}
            caps_disable = {
                "detail_panel": "legacy jwst_gc_aladin.html has no per-source detail panel, "
                                "only a sky view with layer-toggle side panels",
                "source_list_search": "legacy jwst_gc_aladin.html has no source list/search "
                                      "panel, catalogs are toggled as whole overlays",
            }
        return [P(id="jwst_gc_aladin", archetype="explorer", title="JWST GC sky explorer",
                 datasets=datasets, layout=layout, caps_disable=caps_disable)]


ADAPTER = JwstGcAladinAdapter()
