    def pages(self, ctx, ds):
        from portalkit.spec import PageSpec
        pages = []
        for p in ctx.site.portals:
            gal = [g for g in GALLERIES if g.portal == p.id]
            cards = [{"page": g.page, "text": g.blurb} for g in gal]
            cards += [{"href": q.url, "title": q.title, "auth": q.visibility,
                       "text": "Gallery set" + (" (login required)" if q.visibility == "secure" else " (public)")}
                      for q in ctx.site.portals if q.id != p.id]
            pages.append(PageSpec(id="index", archetype="landing", title=p.title, datasets=[f"readme_{p.id}"],
                                  portal=p.id, layout={"pane": "landing", "options": {"cards": cards, "counts": True}}))
            for g in gal:
                n = len(ds[g.page].items)
                extra = ["pngb"] if g.page == "png_b" else []
                nleg = sum(len(s.legacy) for s in g.sources)
                pages.append(PageSpec(id=g.page, archetype="gallery", title=g.title, portal=p.id,
                                      datasets=[g.page] + extra + [f"readme_{p.id}"],
                                      subtitle=f"{n:,} images · {nleg} legacy page{'s' if nleg > 1 else ''}"))
        return pages


