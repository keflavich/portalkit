    def _readme(self, ctx, portal, ds) -> str:
        gal = [g for g in GALLERIES if g.portal == portal.id]
        vis = "public" if portal.visibility == "public" else "secure (login required)"
        lim = "" if ctx.limit is None else f"\n\nFixture build: at most {ctx.limit} images per gallery."
        out = [f"# {portal.title}\n\nUnified galleries of the legacy jQuery directory galleries ({vis}). "
               "Each legacy page is a facet preset of its unified page; the role buttons switch image "
               f"variants.{lim}\n"]
        for g in gal:
            out.append(f"## {g.title}\n\n{g.blurb} {len(ds[g.page].items):,} items.\n")
            fkeys = {k for k, _ in ds[g.page].facets}
            for s in g.sources:
                for lg in s.legacy:
                    rx = "model cards" if s.kind == "pngb" else f"`/{lg.rx}/i`"
                    fix = f"; legacy header \"{lg.header}\" corrected" if lg.header else ""
                    fix += "; lists no image" if lg.subset and facet_key(lg) not in fkeys else ""
                    out.append(f"- [{lg.file}]({legacy_url(portal.visibility, g, lg)}): {rx}{fix}")
            out.append("")
        if portal.id == "brick_2221":
            out.append("The NIRSpec 6927 spectra are in the [NIRSpec 6927 portal]"
                       "(https://data.rc.ufl.edu/secure/adamginsburg/jwst/spectra/nirspec_6927/unified/) "
                       "(login required); this public page holds no secure data.\n")
        return "\n".join(out)

