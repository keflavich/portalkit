def test_inplace_replace_rewrites_urls(world):
    run(world, replace="inplace")
    out = (world["legacy"] / "old_map.html").read_text()
    page = dmod.extract_page_json(out)
    assert page["assets"] == "unified/assets/"
    assert page["datasets"]["src"]["url"] == "unified/data/src/manifest.json"
    assert page["links"]["home"] == "unified/index.html"
    assert 'href="unified/assets/pk.css"' in out
    man = manifest(world)
    assert man["replaced"][0]["mode"] == "inplace"
    assert bmod.read_backup(world["legacy"], BID)["files"][0]["mode"] == "inplace"
    bmod.rollback(world["legacy"], BID, target=world["target"])
    assert (world["legacy"] / "old_map.html").read_text() == LEGACY


def test_rollback_of_newer_build_keeps_it_deployed(world):
    stmod = importlib.import_module("portalkit.deploy.status")
    run(world)
    stage_portal(world["stage"], BID2, "v2")
    run(world, site(world, preset=""), bid=BID2)
    bmod.rollback_portal(FAM, BID2, site(world))
    man = manifest(world)
    assert dmod.deployed_builds(man) == [BID, BID2]
    assert "v2" in (world["target"] / "map.html").read_text()
    row = stmod.portal_status(FAM, site(world), site(world)["portal"][0],
                              stage_root=world["stage"])
    assert row.deployed_build == BID2
    assert "DRIFT" not in row.flags and "NOT-DEPLOYED" not in row.flags


def test_rollback_portal_shared_legacy_dir(world):
    """Section 4.1: a shared legacy_dir deploys to unified/<family>; rollback_portal finds
    that target from backup.json without being told."""
    res = run(world, shared_legacy_dir=True)
    tgt = world["legacy"] / "unified" / FAM
    assert (tgt / dmod.MANIFEST_NAME).is_file()
    assert (world["legacy"] / "old_map.html").read_text() == \
        bmod.stub_html("unified/fam/map.html", "ccd")
    assert res.replaced
    rb = bmod.rollback_portal(FAM, BID, site(world))
    assert rb.restored == ["old_map.html"] and rb.manifest_updated
    man = json.loads((tgt / dmod.MANIFEST_NAME).read_text())
    assert man["replaced"] == []
    # the flag is also accepted explicitly, and the shared-dir helpers detect it
    other = {"family": "other", "portal": [{"id": "o", "legacy_dir": str(world["legacy"])}]}
    entry = site(world)["portal"][0]
    assert dmod.is_shared_legacy_dir(entry, [site(world), other])
    assert not dmod.is_shared_legacy_dir(entry, [site(world)])
    assert dmod.resolve_target(entry, FAM, True) == tgt
    stmod = importlib.import_module("portalkit.deploy.status")
    rows = stmod.status([site(world)], stage_root=world["stage"], all_sites=[site(world), other])
    assert rows[0].target == str(tgt) and rows[0].deployed_build == BID
    assert "NOT-DEPLOYED" not in rows[0].flags


