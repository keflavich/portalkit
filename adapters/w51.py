def _row_spectrum(row: dict | None, lines: list[dict]) -> Spectrum | None:
    """Build the :class:`~portalkit.spec.Spectrum` of one ``spectra.html`` ``specdata`` row.

    The wavelength grid is ``w0 + dw * arange(m)`` (um). ``flux``/``norm``/``normcm`` are
    per-pixel arrays already on that grid; ``nerr``/``ferr`` are *strided* (one value every
    ``es`` pixels, per the legacy page's own despike-block decimation) and are upsampled with
    ``np.repeat(arr, es)`` back onto the pixel grid. ``cmode`` (one float per pixel: the
    common-mode correction applied before ``normcm``) is carried as its own channel.
    """
    if row is None:
        return None
    m = int(row["m"])
    w0, dw = float(row["w0"]), float(row["dw"])
    wave = w0 + dw * np.arange(m, dtype=np.float64)
    flux = np.asarray(row.get("flux") or [np.nan] * m, dtype=np.float64)
    channels: dict[str, np.ndarray] = {"flux": flux}
    for key in ("norm", "normcm", "cmode"):
        arr = row.get(key)
        if arr is not None:
            channels[key] = np.asarray(arr, dtype=np.float64)
    es = int(row.get("es") or 1)
    for strided_key, chan_key in (("nerr", "err"), ("ferr", "e_norm")):
        arr = row.get(strided_key)
        if arr is not None:
            up = np.repeat(np.asarray(arr, dtype=np.float64), max(es, 1))[:m]
            if up.size < m:
                up = np.concatenate([up, np.full(m - up.size, np.nan)])
            channels[chan_key] = up
    meta = {k: row[k] for k in ("tier", "field", "sl", "twod", "suspect", "usable", "placed")
           if k in row}
    return Spectrum(wave=wave, channels=channels,
                    units={"flux": "instrumental count rate"}, lines=lines, meta=meta)


